//! Test fixtures — the canonical small permutation groups.

use perm_core::{Perm, PermGroup, Point};

/// Symmetric `S_n` via `(0,1)` + the n-cycle `(0,1,...,n-1)`.
pub fn symmetric(n: usize) -> PermGroup {
    if n == 0 {
        return PermGroup::from_generators(0, &[]).unwrap();
    }
    if n == 1 {
        return PermGroup::from_generators(1, &[Perm::identity(1)]).unwrap();
    }
    let mut t = (0..n as Point).collect::<Vec<_>>();
    t.swap(0, 1);
    let transp = Perm::from_images(&t).unwrap();
    let mut c = Vec::with_capacity(n);
    for i in 0..n as Point {
        c.push(((i + 1) as usize % n) as Point);
    }
    let cyc = Perm::from_images(&c).unwrap();
    PermGroup::from_generators(n, &[transp, cyc]).unwrap()
}

/// Alternating `A_n` via the standard pair (n >= 3):
/// the 3-cycle `(0,1,2)` and either `(0,1,2,...,n-1)` (n odd) or
/// `(1,2,...,n-1)` (n even).
pub fn alternating(n: usize) -> PermGroup {
    assert!(n >= 2);
    if n == 2 {
        return PermGroup::from_generators(2, &[Perm::identity(2)]).unwrap();
    }
    // (0 1 2)
    let mut a = (0..n as Point).collect::<Vec<_>>();
    a[0] = 1;
    a[1] = 2;
    a[2] = 0;
    let three = Perm::from_images(&a).unwrap();
    // big cycle
    let mut b = (0..n as Point).collect::<Vec<_>>();
    if n % 2 == 1 {
        for i in 0..n as Point {
            b[i as usize] = ((i + 1) as usize % n) as Point;
        }
    } else {
        // (1 2 ... n-1)
        for i in 0..n as Point {
            if i == 0 {
                b[0] = 0;
            } else {
                let next = if (i as usize) == n - 1 { 1 } else { i + 1 };
                b[i as usize] = next as Point;
            }
        }
    }
    let cyc = Perm::from_images(&b).unwrap();
    PermGroup::from_generators(n, &[three, cyc]).unwrap()
}

/// Cyclic `C_n` of order n, generated by the n-cycle.
pub fn cyclic(n: usize) -> PermGroup {
    assert!(n >= 1);
    if n == 1 {
        return PermGroup::from_generators(1, &[Perm::identity(1)]).unwrap();
    }
    let mut c = Vec::with_capacity(n);
    for i in 0..n as Point {
        c.push(((i + 1) as usize % n) as Point);
    }
    let cyc = Perm::from_images(&c).unwrap();
    PermGroup::from_generators(n, &[cyc]).unwrap()
}

/// Dihedral `D_n` (order 2n), acting on `0..n` via rotation +
/// reflection.
pub fn dihedral(n: usize) -> PermGroup {
    assert!(n >= 3);
    // rotation by 1
    let mut r = Vec::with_capacity(n);
    for i in 0..n as Point {
        r.push(((i + 1) as usize % n) as Point);
    }
    let rot = Perm::from_images(&r).unwrap();
    // reflection: i -> (n - i) mod n
    let mut s = Vec::with_capacity(n);
    for i in 0..n as Point {
        s.push(((n - i as usize) % n) as Point);
    }
    let refl = Perm::from_images(&s).unwrap();
    PermGroup::from_generators(n, &[rot, refl]).unwrap()
}

/// Two-generator presentation of `PSL(2, p)` acting on the
/// projective line `P^1(F_p)` ∪ {∞}. Approximated for our parity
/// purposes via:
///
/// - `t: x -> x + 1 mod p`
/// - `s: x -> -1/x` (with `s(0) = ∞`, `s(∞) = 0`).
///
/// The group these generate on a `(p+1)`-point set is `PSL(2, p)`,
/// order `p(p^2-1)/2` for odd p > 2.
#[allow(dead_code)]
pub fn psl2p(p: u32) -> PermGroup {
    let n = (p + 1) as usize;
    // points 0..p, plus "infinity" labelled `p`.
    let infty = p;
    // t: x -> x+1 mod p; t(infty) = infty
    let mut t_img = vec![0u32; n];
    for x in 0..p {
        t_img[x as usize] = (x + 1) % p;
    }
    t_img[infty as usize] = infty;
    // s: x -> -1/x for x != 0; s(0) = infty; s(infty) = 0
    let mut s_img = vec![0u32; n];
    for x in 0..p {
        if x == 0 {
            s_img[0] = infty;
        } else {
            // modular inverse of x mod p
            let inv = mod_inverse(x as i64, p as i64) as u32;
            let neg = (p - inv) % p;
            s_img[x as usize] = neg;
        }
    }
    s_img[infty as usize] = 0;
    let t = Perm::from_images(&t_img).unwrap();
    let s = Perm::from_images(&s_img).unwrap();
    PermGroup::from_generators(n, &[t, s]).unwrap()
}

#[allow(dead_code)]
fn mod_inverse(a: i64, m: i64) -> i64 {
    let (mut old_r, mut r) = (a.rem_euclid(m), m);
    let (mut old_s, mut s) = (1i64, 0i64);
    while r != 0 {
        let q = old_r / r;
        let (nr, ns) = (old_r - q * r, old_s - q * s);
        old_r = r;
        r = nr;
        old_s = s;
        s = ns;
    }
    old_s.rem_euclid(m)
}
