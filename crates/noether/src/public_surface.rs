#[cfg(test)]
mod tests {
    use std::collections::HashSet;

    use super::*;

    fn assert_sorted_unique(values: &[&str]) {
        assert!(values.windows(2).all(|pair| pair[0] < pair[1]));
        assert_eq!(
            values.len(),
            values.iter().copied().collect::<HashSet<_>>().len()
        );
    }

    #[test]
    fn accepted_names_are_sorted_unique_and_disjoint() {
        assert_sorted_unique(accepted_public_types());
        assert_sorted_unique(accepted_operations());
        assert_sorted_unique(accepted_public_values());
        let types = accepted_public_types()
            .iter()
            .copied()
            .collect::<HashSet<_>>();
        let operations = accepted_operations()
            .iter()
            .copied()
            .collect::<HashSet<_>>();
        let values = accepted_public_values()
            .iter()
            .copied()
            .collect::<HashSet<_>>();
        assert!(types.is_disjoint(&operations));
        assert!(types.is_disjoint(&values));
        assert!(operations.is_disjoint(&values));
    }

    #[test]
    fn every_qualified_operation_has_an_accepted_owner() {
        let domains = accepted_domains().iter().copied().collect::<HashSet<_>>();
        let types = accepted_public_types()
            .iter()
            .copied()
            .collect::<HashSet<_>>();
        for operation in accepted_operations() {
            let parts = operation.split('.').collect::<Vec<_>>();
            let owner = if domains.contains(parts[0]) && parts.len() >= 3 {
                Some(format!("{}.{}", parts[0], parts[1]))
            } else if !domains.contains(parts[0]) && parts.len() >= 2 {
                Some(parts[0].to_owned())
            } else {
                None
            };
            if let Some(owner) = owner {
                assert!(
                    types.contains(owner.as_str()),
                    "unaccepted owner {owner} for {operation}"
                );
            }
        }
    }

    #[test]
    fn available_surface_matches_the_compiled_optional_features() {
        assert_eq!(available_public_values(), accepted_public_values());
        assert_eq!(available_domains(), accepted_domains());
        if cfg!(feature = "distributed") {
            assert_eq!(available_public_types(), accepted_public_types());
            assert_eq!(available_operations(), accepted_operations());
        } else {
            assert!(available_public_types()
                .iter()
                .all(|name| is_available(name)));
            assert!(available_operations().iter().all(|name| is_available(name)));
            assert!(!available_public_types().contains(&"linalg.DistributedMatrix"));
            assert!(!available_operations().contains(&"linalg.DistributedMatrix.rank"));
        }
    }
}
