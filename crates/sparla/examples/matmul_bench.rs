//! Benchmark: sparse · sparse vs dense · dense matrix multiplication
//! over `F_p`.
//!
//! Run with `cargo run --release --example matmul_bench` (release is
//! load-bearing — debug numbers are not informative). Each row of
//! output is one (size, density) configuration: actual input nnz,
//! sparse and dense matmul times, and a `dense / sparse` speedup
//! ratio. Speedup `> 1` means the sparse algorithm beats dense at
//! that point on the density/size grid; `< 1` means densify-and-
//! delegate is the better strategy.
//!
//! Inputs are generated by a fixed LCG so runs are reproducible.
//! Sparse and dense results are checked bit-for-bit before timing
//! is reported.

use std::time::Instant;

use sparla::storage::{CsrFp, SparseRingStorage};

const PRIME: u64 = 65537;

struct Lcg(u64);

impl Lcg {
    fn new(seed: u64) -> Self {
        Self(seed)
    }
    fn next(&mut self) -> u64 {
        self.0 = self
            .0
            .wrapping_mul(6364136223846793005)
            .wrapping_add(1442695040888963407);
        self.0 >> 32
    }
}

/// Generate a random `rows × cols` sparse `F_p` matrix at the given
/// density. Density is interpreted as the fraction of *attempted*
/// inserts; duplicate `(r, c)` pairs are summed by `from_coo`, so
/// the actual nnz after canonicalisation may differ slightly at
/// high densities.
fn gen_sparse(rows: usize, cols: usize, density: f64, prime: u64, seed: u64) -> CsrFp {
    let mut rng = Lcg::new(seed);
    let target = ((rows * cols) as f64 * density) as usize;
    let p = prime as i64;
    let mut triples: Vec<(usize, usize, i64)> = Vec::with_capacity(target);
    for _ in 0..target {
        let r = (rng.next() as usize) % rows;
        let c = (rng.next() as usize) % cols;
        let v = (rng.next() as i64 % (p - 1)) + 1;
        triples.push((r, c, v));
    }
    CsrFp::from_coo(rows, cols, &triples, prime)
}

/// Gustavson-style sparse matrix multiplication over `F_p`. For
/// each output row, walk the relevant rows of `b` indexed by the
/// nonzeros of `a`'s row, accumulating into a dense `n`-wide
/// scratch buffer. `touched` tracks which columns were written so
/// the buffer can be reset in `O(nnz per output row)` time.
///
/// Returns the algorithm's natural internal representation
/// (`Vec<Vec<(col, val)>>`, sorted by col within each row). The
/// final CsrFp wrapping is intentionally outside the timed region
/// — both algorithms are clocked for their algorithmic work only.
fn sparse_matmul(a: &CsrFp, b: &CsrFp) -> Vec<Vec<(usize, u32)>> {
    assert_eq!(a.cols(), b.rows());
    assert_eq!(a.modulus(), b.modulus());
    let p = a.modulus();
    let m = a.rows();
    let n = b.cols();

    let mut out_rows: Vec<Vec<(usize, u32)>> = Vec::with_capacity(m);
    let mut acc: Vec<u64> = vec![0; n];
    let mut touched: Vec<usize> = Vec::new();

    for i in 0..m {
        for (k, av) in a.iter_row(i) {
            let av = av as u64;
            for (j, bv) in b.iter_row(k) {
                if acc[j] == 0 {
                    touched.push(j);
                }
                acc[j] = (acc[j] + av * bv as u64) % p;
            }
        }
        touched.sort_unstable();
        touched.dedup();
        let mut row: Vec<(usize, u32)> = Vec::with_capacity(touched.len());
        for &j in &touched {
            let v = acc[j];
            if v != 0 {
                row.push((j, v as u32));
            }
            acc[j] = 0;
        }
        touched.clear();
        out_rows.push(row);
    }

    out_rows
}

/// Densify a sparse-row result for parity comparison against the
/// dense kernel's output.
fn densify_rows(rows: &[Vec<(usize, u32)>], cols: usize) -> Vec<Vec<u32>> {
    rows.iter()
        .map(|row| {
            let mut r = vec![0u32; cols];
            for &(c, v) in row {
                r[c] = v;
            }
            r
        })
        .collect()
}

/// Pure triple-loop dense matrix multiplication. Deliberately
/// avoids any `if av == 0 { continue }` sparsity shortcut so the
/// dense numbers represent the "dense backend treats every cell"
/// baseline.
fn dense_matmul(a: &[Vec<u32>], b: &[Vec<u32>], prime: u64) -> Vec<Vec<u32>> {
    let m = a.len();
    let k = if m == 0 { 0 } else { a[0].len() };
    let n = if b.is_empty() { 0 } else { b[0].len() };
    assert_eq!(b.len(), k);
    let mut c: Vec<Vec<u64>> = vec![vec![0u64; n]; m];
    for i in 0..m {
        for kk in 0..k {
            let av = a[i][kk] as u64;
            for j in 0..n {
                c[i][j] = (c[i][j] + av * b[kk][j] as u64) % prime;
            }
        }
    }
    c.into_iter()
        .map(|row| row.into_iter().map(|v| v as u32).collect())
        .collect()
}

fn main() {
    println!(
        "sparse · sparse vs dense · dense matmul over F_p (p = {})",
        PRIME
    );
    println!();
    println!(
        "{:>6} {:>9} {:>10} {:>10} {:>10} {:>10} {:>10}",
        "size", "density", "A nnz", "B nnz", "sparse ms", "dense ms", "speedup"
    );
    println!("{}", "-".repeat(72));

    let configs: &[(usize, f64)] = &[
        (50, 0.01),
        (50, 0.05),
        (50, 0.25),
        (50, 1.00),
        (100, 0.01),
        (100, 0.05),
        (100, 0.25),
        (100, 1.00),
        (200, 0.01),
        (200, 0.05),
        (200, 0.25),
        (500, 0.001),
        (500, 0.01),
        (500, 0.05),
        (1000, 0.001),
        (1000, 0.01),
    ];

    for &(n, density) in configs {
        let a = gen_sparse(n, n, density, PRIME, 0xC0FF_EE42);
        let b = gen_sparse(n, n, density, PRIME, 0xBAAD_F00D);
        let a_dense = a.to_dense();
        let b_dense = b.to_dense();

        let t0 = Instant::now();
        let c_sparse_rows = sparse_matmul(&a, &b);
        let sparse_ms = t0.elapsed().as_secs_f64() * 1000.0;

        let t0 = Instant::now();
        let c_dense = dense_matmul(&a_dense, &b_dense, PRIME);
        let dense_ms = t0.elapsed().as_secs_f64() * 1000.0;

        assert_eq!(
            densify_rows(&c_sparse_rows, n),
            c_dense,
            "sparse and dense disagree at n = {}, density = {}",
            n,
            density
        );

        let speedup = dense_ms / sparse_ms.max(1e-6);
        println!(
            "{:>6} {:>8.2}% {:>10} {:>10} {:>10.2} {:>10.2} {:>9.2}x",
            n,
            density * 100.0,
            a.nnz(),
            b.nnz(),
            sparse_ms,
            dense_ms,
            speedup
        );
    }
}
