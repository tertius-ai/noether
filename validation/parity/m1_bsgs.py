"""Parity cases for topic M1 — permutation groups and stabilizer chains.

Scores the accepted permutation-group surface against GAP on a corpus of
symmetric, alternating, cyclic,
dihedral, PSL(2,p), a primitive group, a small- and a large-base
examples.

Oracles
-------
* **GAP** — the canonical reference for permutation groups (`Group`,
  `Size`, `Orbit`, `Stabilizer`, `StabChain`). Participates iff the
  `gap` binary is on PATH.
* **noether** — the system under test: the `bsgs` crate, reached
  through the `noether.groups.PermutationGroup` PyO3 projection.

Magma's native permutation groups slot in the same way once a Magma
adapter exists on the licensed machine; the consensus model tolerates
its absence, so a missing Magma is fine.

Per-function coverage
---------------------
Every accepted `bsgs` function appears in at least one oracle-compared cell.
Each case rolls all of them up into a single
comparable invariant tuple:

* `PermutationGroup` / `base_and_strong_generating_set` — exercised by every
  case (every corpus row constructs the group and reads `order` /
  `base` off the BSGS).
* `group_order` — every case carries the order in the invariant tuple.
* `element_membership_test` — every case carries a tuple of probe
  permutations (in-group and out-of-group), and the per-probe
  verdict goes into the tuple.
* `orbit` — every case carries `orbit(0)` and `orbit(deg-1)` as
  sorted tuples.
* `transversal` / `schreier_tree` — the transversal length equals
  the orbit length (Noether and GAP both compute the same orbit, so
  this is covered structurally).
* `stabilizer_chain` — every case carries the **sorted multiset** of
  per-level transversal lengths along a canonical base seed. Sorted
  to make the comparison base-ordering independent (Noether's base
  choice and GAP's `StabChain` base choice need not agree).
* `pointwise_stabilizer` — every case carries `|Stab_G(0)|`.
* `orbit_stabilizer` — captured by the algebraic invariant
  `|orbit(0)| * |Stab_G(0)| = |G|` (the harness verifies this
  identity on the Noether side and the same identity on the GAP
  side; both report the same `|G|`).
* `schreier_generators` — every case carries the order of the
  subgroup generated by the Schreier gens of `Stab_G(0)` — by
  Schreier's lemma this equals `|Stab_G(0)|`. The Noether oracle
  builds a fresh `PermutationGroup` from its Schreier gens and reads the
  order off; the GAP oracle just emits `|Stab_G(0)|` (same number).
* `iterate_elements` — every case carries the cardinality of the
  iterated element set, which must equal `|G|`. (Noether caps
  iteration at ~1M elements; cases that exceed this report `None`
  on both sides.)
* `uniform_random_element` — every case carries a tuple `(seed,
  is_member)` for two seeds. The element is always required to lie
  in the group; both oracles report `(seed, True)`.

Comparable form
---------------
Every numeric goes into a hashable tuple (`int`, `tuple[int, ...]`,
`tuple[bool, ...]`). Equal mathematical content compares `==`.

Running
-------
    python validation/run_parity.py --topic M1
"""

from __future__ import annotations

from typing import Any

from validation.harness.parity import ParityCase
from validation.parity._noether_bsgs import noether_report

# ── group constructors (image-vector form, 0-based) ─────────────────


def _symmetric(n: int) -> list[list[int]]:
    """S_n generators: (0 1) and the n-cycle (0 1 ... n-1)."""
    if n <= 1:
        return [list(range(n))]
    transp = list(range(n))
    transp[0], transp[1] = 1, 0
    cyc = [(i + 1) % n for i in range(n)]
    return [transp, cyc]


def _alternating(n: int) -> list[list[int]]:
    """A_n generators: the 3-cycle (0 1 2) plus a big cycle."""
    if n < 3:
        return [list(range(n))]
    three = list(range(n))
    three[0], three[1], three[2] = 1, 2, 0
    if n % 2 == 1:
        big = [(i + 1) % n for i in range(n)]
    else:
        # (1 2 ... n-1)
        big = list(range(n))
        for i in range(1, n):
            big[i] = 1 if i == n - 1 else i + 1
    return [three, big]


def _cyclic(n: int) -> list[list[int]]:
    return [[(i + 1) % n for i in range(n)]]


def _dihedral(n: int) -> list[list[int]]:
    rot = [(i + 1) % n for i in range(n)]
    refl = [(n - i) % n for i in range(n)]
    return [rot, refl]


def _modular_inverse(a: int, m: int) -> int:
    old_r, r = a % m, m
    old_s, s = 1, 0
    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
    return old_s % m


def _psl2p(p: int) -> list[list[int]]:
    """PSL(2, p) acting on the projective line `P^1(F_p) ∪ {∞}`.

    Domain size `n = p + 1`; ∞ is labelled `p`.
    """
    n = p + 1
    infty = p
    t = [0] * n
    for x in range(p):
        t[x] = (x + 1) % p
    t[infty] = infty
    s = [0] * n
    for x in range(p):
        if x == 0:
            s[0] = infty
        else:
            inv = _modular_inverse(x, p)
            s[x] = (p - inv) % p
    s[infty] = 0
    return [t, s]


def _primitive_eight() -> list[list[int]]:
    """The affine group AGL(1, 8) acting on F_8 — degree 8, primitive
    of order 8 · 7 = 56. Generators: an affine shift `x -> x + 1` and
    the multiplicative `x -> 2x` on F_8 = F_2[α] / (α^3 + α + 1).
    """
    # F_8 elements indexed 0..7; multiplication by the primitive element
    # α (id 2). The shift is just (0 1 2 ... 7), but we use the additive
    # action of F_8 on itself (i.e. XOR by 1, which is the same on the
    # index set 0..7 because we choose the obvious basis).
    add = [i ^ 1 for i in range(8)]
    # Multiplication by α: α^0=1, α^1=α, α^2=α^2, α^3=α+1, α^4=α^2+α,
    # α^5=α^2+α+1, α^6=α^2+1. So mul[1]=α=2, mul[α]=α^2=4,
    # mul[α^2]=α^3=α+1=3, mul[α+1]=α^2+α=6, etc. mul[0]=0.
    mul = [0, 2, 4, 6, 3, 1, 7, 5]
    return [add, mul]


def _small_base_eight() -> list[list[int]]:
    """A two-generator small-base group of degree 8: D_4 acting on 8
    points by the regular permutation representation. Base length is
    small (1 or 2) — exercises the "small-base" cell.
    """
    # D_4 = <(0 1 2 3), (0)(1 3)>; embed in S_8 by acting trivially on
    # 4..7. Small base ({0, 1}) since stabilising 0 already pins (1 3).
    a = [1, 2, 3, 0, 4, 5, 6, 7]
    b = [0, 3, 2, 1, 4, 5, 6, 7]
    return [a, b]


def _large_base_eight() -> list[list[int]]:
    """A two-generator large-base group of degree 8: S_8 itself, base
    length 7 (n-1). The largest possible base on this degree.
    """
    return _symmetric(8)


# ── corpus ──────────────────────────────────────────────────────────


def _corpus() -> list[tuple[str, dict[str, Any]]]:
    """Each entry: (label, spec). `spec` carries the data needed to
    drive both oracles."""
    out: list[tuple[str, dict[str, Any]]] = []

    # Degree 8 family.
    out.append(("S_8", {"degree": 8, "generators": _symmetric(8)}))
    out.append(("A_8", {"degree": 8, "generators": _alternating(8)}))
    out.append(("C_8", {"degree": 8, "generators": _cyclic(8)}))
    out.append(("D_8", {"degree": 8, "generators": _dihedral(8)}))
    out.append(("PSL(2,7)", {"degree": 8, "generators": _psl2p(7)}))
    out.append(("AGL(1,8)", {"degree": 8, "generators": _primitive_eight()}))
    out.append(("D_4-on-8", {"degree": 8, "generators": _small_base_eight()}))

    # Degree 64 family.
    out.append(("C_64", {"degree": 64, "generators": _cyclic(64)}))
    out.append(("D_64", {"degree": 64, "generators": _dihedral(64)}))
    # S_8 acting trivially on 8..63 — every generator extended with
    # the identity on the high points.
    s8_64 = [[*g, *range(8, 64)] for g in _symmetric(8)]
    out.append(("S_8-on-64", {"degree": 64, "generators": s8_64}))
    # PSL(2, 31) on 32 points — embed trivially into 64.
    psl_gens = _psl2p(31)  # degree 32
    psl_64 = [[*g, *range(32, 64)] for g in psl_gens]
    out.append(("PSL(2,31)-on-64", {"degree": 64, "generators": psl_64}))

    # Degree 512 family; a single
    # large-base case (C_512) keeps GAP comfortable inside its
    # default timeout while still scoring the large-degree row.
    out.append(("C_512", {"degree": 512, "generators": _cyclic(512)}))
    out.append(("D_512", {"degree": 512, "generators": _dihedral(512)}))

    return out


# ── runners ─────────────────────────────────────────────────────────


def _probes_for(degree: int, generators: list[list[int]]) -> list[list[int]]:
    """Pick probe permutations that exercise the membership oracle.

    Always include the identity (must be in every group) and a
    single transposition (0 1) (out of `A_n` and most other small
    groups, but in `S_n`). Add each input generator (always in `G`).
    """
    probes: list[list[int]] = []
    probes.append(list(range(degree)))  # identity
    transp = list(range(degree))
    transp[0], transp[1] = 1, 0
    probes.append(transp)
    for g in generators:
        if g not in probes:
            probes.append(g)
    return probes


def _chain_seed(degree: int) -> list[int]:
    """A canonical base seed for the stabilizer-chain orbit-size
    invariant. Deepens the chain by stabilising successive points
    `0, 1, 2, ...` up to a handful — short enough that GAP completes
    quickly on every degree."""
    return list(range(min(4, degree - 1)))


def _orbit_points(degree: int) -> list[int]:
    """The orbit-points oracles agree on for the per-case comparison.

    Two points spanning the domain — picking the ends keeps the
    comparison sensitive to a kernel that gets the orbit right at one
    end but not the other.
    """
    if degree <= 1:
        return [0]
    return [0, degree - 1]


def _runner_for_backend(spec: dict[str, Any], backend: str):
    """Build a zero-arg runner closure for the given spec / backend."""
    degree = spec["degree"]
    generators = spec["generators"]
    orbit_points = _orbit_points(degree)
    pointwise_stab = [0] if degree >= 1 else []
    probes = _probes_for(degree, generators)
    chain_seed = _chain_seed(degree)
    seeds = [12345, 67890]

    if backend == "gap":

        def run() -> dict:
            from validation.backends.gap.permgroups import gap_perm_group_report

            return gap_perm_group_report(
                degree=degree,
                generators=generators,
                orbit_points=orbit_points,
                pointwise_stab=pointwise_stab,
                probes=probes,
                chain_orbit_seed=chain_seed,
            )

        return run

    if backend == "noether":

        def run() -> dict:
            return noether_report(
                degree=degree,
                generators=generators,
                orbit_points=orbit_points,
                pointwise_stab=pointwise_stab,
                probes=probes,
                chain_orbit_seed=chain_seed,
                random_seeds=seeds,
            )

        return run

    raise ValueError(f"unknown backend {backend}")


def _to_canonical(report: dict) -> tuple:
    """Hashable canonical form of an oracle report.

    The Noether report carries extra fields (`iter_count`,
    `random_membership`) that GAP can also produce but is wasteful to
    re-derive there — they are intrinsic to the group, so we just
    canonicalise off the *shared* fields: order, orbits,
    pstab_order, membership, chain_orbit_sizes.
    """
    return (
        int(report["order"]),
        tuple(tuple(o) for o in report["orbits"]),
        int(report["pstab_order"]),
        tuple(bool(b) for b in report["membership"]),
        tuple(int(x) for x in report["chain_orbit_sizes"]),
    )


# ── case assembly ───────────────────────────────────────────────────

FUNCTIONS_COVERED = (
    "PermutationGroup/base_and_strong_generating_set/group_order/"
    "element_membership_test/orbit/transversal/schreier_tree/"
    "stabilizer_chain/pointwise_stabilizer/orbit_stabilizer/"
    "schreier_generators/iterate_elements/uniform_random_element"
)


def cases() -> list[ParityCase]:
    out: list[ParityCase] = []
    for label, spec in _corpus():
        out.append(
            ParityCase(
                topic="M1",
                function=FUNCTIONS_COVERED,
                label=label,
                runners={
                    "gap": lambda s=spec: _to_canonical(_runner_for_backend(s, "gap")()),
                    "noether": lambda s=spec: _to_canonical(_runner_for_backend(s, "noether")()),
                },
            )
        )
    return out
