//! Rust-owned acceptance index for the public language surface.
//!
//! The lists here answer which mathematical domains, types, operations and
//! root values belong to Noether's versioned surface. Language bindings enrich
//! these identities with language-specific signatures and documentation, but
//! may not add another accepted name. The available lists remove names whose
//! optional Rust feature is absent from the compiled artifact.

fn is_available(name: &str) -> bool {
    cfg!(feature = "distributed")
        || !(name.starts_with("linalg.Distributed")
            || name == "linalg.MpiThreadSupport"
            || name.starts_with("linalg.MpiThreadSupport.")
            || name == "linalg.World"
            || name.starts_with("linalg.World."))
}

/// Accepted mathematical domains, in stable display order.
pub const fn accepted_domains() -> &'static [&'static str] {
    &[
        "category", "combin", "commalg", "geometry", "groups", "homalg", "linalg", "numthy",
        "topology",
    ]
}

/// Mathematical domains available in this compiled artifact.
#[must_use]
pub fn available_domains() -> Vec<&'static str> {
    accepted_domains()
        .iter()
        .copied()
        .filter(|name| is_available(name))
        .collect()
}

