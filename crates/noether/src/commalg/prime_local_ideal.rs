fn deserialize_prime_local_ideal<'de, R, D>(
    deserializer: D,
) -> Result<PolynomialPrimeLocalIdeal<R>, D::Error>
where
    R: crate::Field + Deserialize<'de>,
    R::Element: Deserialize<'de>,
    PolynomialPrimeLocalization<R>: Deserialize<'de>,
    Ideal<super::PolynomialRing<R>>: Deserialize<'de>,
    D: Deserializer<'de>,
{
    let wire = PolynomialPrimeLocalIdealWire::<R>::deserialize(deserializer)?;
    if wire.type_id != PRIME_LOCAL_IDEAL_TYPE_ID {
        return Err(serde::de::Error::custom(format!(
            "expected type {}, received {}",
            PRIME_LOCAL_IDEAL_TYPE_ID, wire.type_id
        )));
    }
    let generators = wire
        .ambient_ideal
        .generators()
        .iter()
        .cloned()
        .map(|value| wire.ring.from_polynomial(value))
        .collect::<Result<Vec<_>, _>>()
        .map_err(serde::de::Error::custom)?;
    let rebuilt = PolynomialPrimeLocalIdeal::from_generators(wire.ring, &generators)
        .map_err(serde::de::Error::custom)?;
    if rebuilt.ambient_ideal != wire.ambient_ideal {
        return Err(serde::de::Error::custom(
            "serialized prime-local ideal was not canonical",
        ));
    }
    Ok(rebuilt)
}

/// Exact yes/no evidence for membership in a polynomial prime-local ideal.
///
/// In the member case `multiplier` is a local unit and
/// `multiplier * value = sum(quotients[i] * ideal.generators()[i])`.
/// In the nonmember case every canonical generator of `colon_ideal` lies in
/// the localization prime, proving that no admissible multiplier exists.
#[derive(Clone, PartialEq, Eq)]
pub struct PolynomialPrimeLocalMembership<R: crate::Field> {
    ideal: PolynomialPrimeLocalIdeal<R>,
    value: PolynomialPrimeLocalElement<R>,
    colon_ideal: Ideal<super::PolynomialRing<R>>,
    multiplier: Option<PolynomialPrimeLocalElement<R>>,
    quotients: Vec<PolynomialPrimeLocalElement<R>>,
}

impl<R: crate::Field> PolynomialPrimeLocalMembership<R> {
    /// Local ideal whose membership was tested.
    pub fn ideal(&self) -> &PolynomialPrimeLocalIdeal<R> {
        &self.ideal
    }

    /// Exact tested value.
    pub fn value(&self) -> &PolynomialPrimeLocalElement<R> {
        &self.value
    }

    /// Canonical ambient colon ideal `(I : numerator(value))`.
    pub fn colon_ideal(&self) -> &Ideal<super::PolynomialRing<R>> {
        &self.colon_ideal
    }

    /// Unit membership multiplier, present exactly in the member case.
    pub fn multiplier(&self) -> Option<&PolynomialPrimeLocalElement<R>> {
        self.multiplier.as_ref()
    }

    /// Coefficients against the canonical local generators.
    pub fn quotients(&self) -> &[PolynomialPrimeLocalElement<R>] {
        &self.quotients
    }

    /// Whether the colon ideal contains an element outside the prime.
    pub const fn is_member(&self) -> bool {
        self.multiplier.is_some()
    }

    fn verify_identity(&self) -> Result<(), PrimeLocalizationError> {
        if self.value.ring() != self.ideal.ring() {
            return Err(PrimeLocalizationError::InvalidEvidence(
                "membership evidence crosses prime-local contexts".to_owned(),
            ));
        }
        match &self.multiplier {
            Some(multiplier) => {
                if !multiplier.is_unit()? {
                    return Err(PrimeLocalizationError::InvalidEvidence(
                        "the retained membership multiplier is not a local unit".to_owned(),
                    ));
                }
                let generators = self.ideal.generators()?;
                if generators.len() != self.quotients.len() {
                    return Err(PrimeLocalizationError::InvalidEvidence(
                        "membership coefficient count does not match the canonical generators"
                            .to_owned(),
                    ));
                }
                let left = (multiplier * &self.value)?;
                let right = generators.iter().zip(&self.quotients).try_fold(
                    self.ideal.ring().zero(),
                    |sum, (generator, quotient)| {
                        let product = (generator * quotient)?;
                        &sum + &product
                    },
                )?;
                if left != right {
                    return Err(PrimeLocalizationError::InvalidEvidence(
                        "membership coefficients do not replay the unit-multiplier identity"
                            .to_owned(),
                    ));
                }
            }
            None => {
                if !self.quotients.is_empty() {
                    return Err(PrimeLocalizationError::InvalidEvidence(
                        "nonmembership evidence retained irrelevant coefficients".to_owned(),
                    ));
                }
                for generator in self.colon_ideal.generators() {
                    if !self.ideal.ring().prime().ideal().contains(generator)? {
                        return Err(PrimeLocalizationError::InvalidEvidence(
                            "a nonmembership colon generator lies outside the localization prime"
                                .to_owned(),
                        ));
                    }
                }
            }
        }
        Ok(())
    }

    /// Recompute the colon criterion and the canonical evidence.
    pub fn verify(&self) -> Result<(), PrimeLocalizationError> {
        self.verify_identity()?;
        let rebuilt = self.ideal.certify_membership(&self.value)?;
        if rebuilt != *self {
            return Err(PrimeLocalizationError::InvalidEvidence(
                "recomputation changed prime-local membership evidence".to_owned(),
            ));
        }
        Ok(())
    }

    /// Serialize exact local-membership evidence.
    pub fn to_json(&self) -> Result<String, NoetherError>
    where
        R: Serialize,
        R::Element: Serialize,
        Ideal<super::PolynomialRing<R>>: Serialize,
    {
        serde_json::to_string(self).map_err(|error| NoetherError::Serialization(error.to_string()))
    }
}

