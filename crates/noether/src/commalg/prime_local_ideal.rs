impl<R: crate::Field> PolynomialPrimeLocalization<R> {
    /// Construct the canonical ideal generated by exact local fractions.
    pub fn ideal(
        &self,
        generators: &[PolynomialPrimeLocalElement<R>],
    ) -> Result<PolynomialPrimeLocalIdeal<R>, PrimeLocalizationError> {
        PolynomialPrimeLocalIdeal::from_generators(self.clone(), generators)
    }
}

/// A canonical finitely generated ideal in `k[x_1,...,x_n]_p`.
///
/// Every denominator of an admitted generator is a unit, so the canonical
/// generators are the reduced Groebner basis of their numerator ideal in the
/// ambient polynomial ring. This is identity, not an implementation claim
/// about a mixed local/global standard basis.
#[derive(Clone, PartialEq, Eq)]
pub struct PolynomialPrimeLocalIdeal<R: crate::Field> {
    ring: PolynomialPrimeLocalization<R>,
    ambient_ideal: Ideal<super::PolynomialRing<R>>,
}

impl<R: crate::Field> PolynomialPrimeLocalIdeal<R> {
    /// Construct the canonical ideal generated by exact local fractions.
    pub fn from_generators(
        ring: PolynomialPrimeLocalization<R>,
        generators: &[PolynomialPrimeLocalElement<R>],
    ) -> Result<Self, PrimeLocalizationError> {
        if generators.iter().any(|value| value.ring() != &ring) {
            return Err(PrimeLocalizationError::InvalidEvidence(
                "a prime-local ideal generator belongs to another context".to_owned(),
            ));
        }
        let ambient_ideal = ring
            .ambient_ring()
            .ideal(generators.iter().map(|value| value.numerator().clone()))?;
        Ok(Self {
            ring,
            ambient_ideal,
        })
    }

    /// Exact prime-local coefficient context.
    pub fn ring(&self) -> &PolynomialPrimeLocalization<R> {
        &self.ring
    }

    /// Canonical ambient numerator ideal.
    pub fn ambient_ideal(&self) -> &Ideal<super::PolynomialRing<R>> {
        &self.ambient_ideal
    }

    /// Canonical local generators, each with denominator one.
    pub fn generators(
        &self,
    ) -> Result<Vec<PolynomialPrimeLocalElement<R>>, PrimeLocalizationError> {
        self.ambient_ideal
            .generators()
            .iter()
            .cloned()
            .map(|value| self.ring.from_polynomial(value))
            .collect()
    }

    /// Certify membership by the exact colon criterion.
    ///
    /// For `value = f/d`, membership is equivalent to
    /// `(ambient_ideal : f)` not being contained in the localization prime.
    /// The first canonical colon generator outside the prime is retained as
    /// the unit multiplier in a replayable local linear-combination identity.
    pub fn certify_membership(
        &self,
        value: &PolynomialPrimeLocalElement<R>,
    ) -> Result<PolynomialPrimeLocalMembership<R>, PrimeLocalizationError> {
        if value.ring() != &self.ring {
            return Err(PrimeLocalizationError::InvalidEvidence(
                "a membership value belongs to another prime-local context".to_owned(),
            ));
        }
        let principal = self
            .ring
            .ambient_ring()
            .ideal([value.numerator().clone()])?;
        let colon_ideal = self.ambient_ideal.colon(&principal)?;
        let witness = colon_ideal
            .generators()
            .iter()
            .find_map(
                |candidate| match self.ring.prime().ideal().contains(candidate) {
                    Ok(false) => Some(Ok(candidate.clone())),
                    Ok(true) => None,
                    Err(error) => Some(Err(error)),
                },
            )
            .transpose()?;
        let (multiplier, quotients) = if let Some(witness) = witness {
            let product = (&witness * value.numerator())?;
            let reduction = self.ambient_ideal.reduce(&product)?;
            if !reduction.is_member() {
                return Err(PrimeLocalizationError::InvalidEvidence(
                    "a colon witness did not multiply the value numerator into the ideal"
                        .to_owned(),
                ));
            }
            let multiplier = self.ring.from_polynomial(witness)?;
            let quotients = reduction
                .multipliers()
                .iter()
                .cloned()
                .map(|numerator| self.ring.fraction(numerator, value.denominator().clone()))
                .collect::<Result<Vec<_>, _>>()?;
            (Some(multiplier), quotients)
        } else {
            (None, Vec::new())
        };
        let result = PolynomialPrimeLocalMembership {
            ideal: self.clone(),
            value: value.clone(),
            colon_ideal,
            multiplier,
            quotients,
        };
        result.verify_identity()?;
        Ok(result)
    }

    /// Decide exact membership in this localized ideal.
    pub fn contains(
        &self,
        value: &PolynomialPrimeLocalElement<R>,
    ) -> Result<bool, PrimeLocalizationError> {
        Ok(self.certify_membership(value)?.is_member())
    }

    /// Recompute the canonical numerator ideal.
    pub fn verify(&self) -> Result<(), PrimeLocalizationError> {
        let generators = self.generators()?;
        let rebuilt = Self::from_generators(self.ring.clone(), &generators)?;
        if rebuilt != *self {
            return Err(PrimeLocalizationError::InvalidEvidence(
                "recomputation changed a prime-local ideal".to_owned(),
            ));
        }
        Ok(())
    }

    /// Serialize the canonical local ideal.
    pub fn to_json(&self) -> Result<String, NoetherError>
    where
        R: Serialize,
        R::Element: Serialize,
        Ideal<super::PolynomialRing<R>>: Serialize,
    {
        serde_json::to_string(self).map_err(|error| NoetherError::Serialization(error.to_string()))
    }
}

