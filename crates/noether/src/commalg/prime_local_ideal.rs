#[cfg(test)]
mod tests {
    use crate::commalg::{MonomialOrder, PolynomialRing};
    use crate::Q;

    use super::*;

    #[test]
    fn colon_witness_certifies_membership_at_a_nonmaximal_prime() {
        let ambient = PolynomialRing::new(Q, ["x", "y"], MonomialOrder::default()).unwrap();
        let [x, y] = ambient.generators().unwrap().try_into().unwrap();
        let prime_ideal = ambient.ideal([x.clone()]).unwrap();
        let prime = prime_ideal.minimal_primes().unwrap().prime_certificates()[0].clone();
        let local = PolynomialPrimeLocalization::new(prime);
        let generator = local.from_polynomial((&x * &y).unwrap()).unwrap();
        let ideal =
            PolynomialPrimeLocalIdeal::from_generators(local.clone(), &[generator]).unwrap();
        let local_x = local.from_polynomial(x.clone()).unwrap();

        let member = ideal.certify_membership(&local_x).unwrap();
        assert!(member.is_member());
        assert!(member.multiplier().unwrap().is_unit().unwrap());
        member.verify().unwrap();
        assert!(ideal.contains(&local_x).unwrap());

        let one = local.one();
        let nonmember = ideal.certify_membership(&one).unwrap();
        assert!(!nonmember.is_member());
        nonmember.verify().unwrap();
        assert!(!ideal.contains(&one).unwrap());

        assert_eq!(
            PolynomialPrimeLocalIdeal::<crate::RationalField>::from_json(&ideal.to_json().unwrap())
                .unwrap(),
            ideal
        );
        assert_eq!(
            PolynomialPrimeLocalMembership::<crate::RationalField>::from_json(
                &member.to_json().unwrap()
            )
            .unwrap(),
            member
        );
    }
}
