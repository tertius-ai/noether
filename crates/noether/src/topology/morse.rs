//! Exact discrete Morse models for finite simplicial complexes.

use core::cmp::Reverse;
use core::fmt;
use std::collections::{BTreeMap, BinaryHeap};

use crate::homalg::ChainComplex;
use crate::linalg::{Matrix, SparseMatrix};
use crate::{Ring, VerificationError};

use super::{SimplicialComplex, TopologyError};

/// Verified critical-cell chain model of a simplicial complex.
#[derive(Clone, PartialEq, Eq)]
pub struct SimplicialMorseReduction<R: Ring> {
    source: SimplicialComplex,
    reduced: ChainComplex<R>,
    matching: MorseMatching,
}

impl<R: Ring> SimplicialMorseReduction<R> {
    /// Source simplicial complex.
    #[must_use]
    pub const fn source(&self) -> &SimplicialComplex {
        &self.source
    }

    /// Chain complex generated by the critical cells.
    #[must_use]
    pub const fn reduced(&self) -> &ChainComplex<R> {
        &self.reduced
    }

    /// Number of nonempty simplices before reduction.
    #[must_use]
    pub fn original_cells(&self) -> usize {
        self.source.total_cells()
    }

    /// Number of critical cells in each simplicial dimension.
    #[must_use]
    pub fn critical_cells(&self) -> Vec<usize> {
        self.matching.critical.iter().map(Vec::len).collect()
    }

    /// Number of matched face/coface pairs.
    #[must_use]
    pub fn matched_pairs(&self) -> usize {
        self.matching
            .up
            .iter()
            .filter(|entry| entry.is_some())
            .count()
    }

    /// Consume the reduction and return its critical-cell chain complex.
    #[must_use]
    pub fn into_reduced(self) -> ChainComplex<R> {
        self.reduced
    }

    /// Recheck the matching, its acyclicity order, and the Morse boundary.
    pub fn verify(&self) -> Result<(), VerificationError> {
        let index = MorseIndex::build(&self.source);
        if !self.matching.verify(&index) {
            return Err(VerificationError::InvalidWitness {
                claim: "simplicial Morse matching is an acyclic cell partition",
            });
        }
        let boundaries = morse_boundaries(&index, &self.matching, self.reduced.ring().clone())
            .map_err(|_| VerificationError::InvalidWitness {
                claim: "simplicial Morse gradient paths reconstruct over the coefficient ring",
            })?;
        let rebuilt =
            dense_chain_complex(self.reduced.ring().clone(), &boundaries).map_err(|_| {
                VerificationError::InvalidWitness {
                    claim: "simplicial Morse boundaries form the recorded chain complex",
                }
            })?;
        if rebuilt != self.reduced {
            return Err(VerificationError::InvalidWitness {
                claim: "simplicial Morse boundary equals the recorded reduced complex",
            });
        }
        self.reduced.verify()
    }
}

impl<R: Ring> fmt::Debug for SimplicialMorseReduction<R> {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter
            .debug_struct("SimplicialMorseReduction")
            .field("original_cells", &self.original_cells())
            .field("critical_cells", &self.critical_cells())
            .field("matched_pairs", &self.matched_pairs())
            .finish()
    }
}

#[derive(Clone, PartialEq, Eq)]
struct MorseMatching {
    critical: Vec<Vec<usize>>,
    up: Vec<Option<usize>>,
    down: Vec<Option<usize>>,
    removal_order: Vec<usize>,
}

impl MorseMatching {
    fn verify(&self, index: &MorseIndex) -> bool {
        if self.up.len() != index.cells
            || self.down.len() != index.cells
            || self.removal_order.len() != index.cells
            || self.critical.len() != index.offset.len().saturating_sub(1)
        {
            return false;
        }
        let mut critical = vec![false; index.cells];
        for (dimension, cells) in self.critical.iter().enumerate() {
            for &cell in cells {
                if cell >= index.cells || index.dimension[cell] != dimension || critical[cell] {
                    return false;
                }
                critical[cell] = true;
            }
        }
        let mut seen_order = vec![false; index.cells];
        for &order in &self.removal_order {
            if order >= index.cells || seen_order[order] {
                return false;
            }
            seen_order[order] = true;
        }

        for (cell, &is_critical) in critical.iter().enumerate() {
            let states = usize::from(self.up[cell].is_some())
                + usize::from(self.down[cell].is_some())
                + usize::from(is_critical);
            if states != 1 {
                return false;
            }
            if let Some(coface) = self.up[cell] {
                if coface >= index.cells
                    || self.down[coface] != Some(cell)
                    || index.dimension[coface] != index.dimension[cell] + 1
                    || !index.faces[coface].iter().any(|&(face, _)| face == cell)
                {
                    return false;
                }
                for &(other_face, _) in &index.faces[coface] {
                    if other_face != cell
                        && self.removal_order[other_face] <= self.removal_order[cell]
                    {
                        return false;
                    }
                }
            }
            if let Some(face) = self.down[cell] {
                if face >= index.cells || self.up[face] != Some(cell) {
                    return false;
                }
            }
        }
        true
    }
}

struct MorseIndex {
    offset: Vec<usize>,
    dimension: Vec<usize>,
    faces: Vec<Vec<(usize, bool)>>,
    cofaces: Vec<Vec<usize>>,
    cells: usize,
}

impl MorseIndex {
    fn build(complex: &SimplicialComplex) -> Self {
        let dimensions = complex.simplices.len();
        let mut offset = vec![0usize; dimensions + 1];
        for dimension in 0..dimensions {
            offset[dimension + 1] = offset[dimension] + complex.count(dimension);
        }
        let cells = offset[dimensions];
        let mut cell_dimension = vec![0usize; cells];
        let mut faces = vec![Vec::new(); cells];
        let mut cofaces = vec![Vec::new(); cells];
        for dimension in 0..dimensions {
            for (local, simplex) in complex.simplices(dimension).iter().enumerate() {
                let cell = offset[dimension] + local;
                cell_dimension[cell] = dimension;
                if dimension == 0 {
                    continue;
                }
                for (omitted, face) in simplex.faces().iter().enumerate() {
                    let face_local = complex
                        .position(face)
                        .expect("a simplicial complex contains every face");
                    let face_cell = offset[dimension - 1] + face_local;
                    faces[cell].push((face_cell, omitted % 2 == 0));
                    cofaces[face_cell].push(cell);
                }
            }
        }
        Self {
            offset,
            dimension: cell_dimension,
            faces,
            cofaces,
            cells,
        }
    }
}

pub(super) fn reduce<R: Ring>(
    complex: &SimplicialComplex,
    ring: R,
) -> Result<SimplicialMorseReduction<R>, TopologyError> {
    let index = MorseIndex::build(complex);
    let matching = build_matching(&index);
    let boundaries = morse_boundaries(&index, &matching, ring.clone())?;
    let reduced = dense_chain_complex(ring, &boundaries)?;
    let result = SimplicialMorseReduction {
        source: complex.clone(),
        reduced,
        matching,
    };
    debug_assert!(result.verify().is_ok());
    Ok(result)
}

pub(super) fn integral_sparse_boundaries_when<F>(
    complex: &SimplicialComplex,
    select: F,
) -> Result<Option<BTreeMap<i32, SparseMatrix<crate::IntegerRing>>>, TopologyError>
where
    F: FnOnce(&[usize]) -> bool,
{
    let index = MorseIndex::build(complex);
    let matching = build_matching(&index);
    debug_assert!(matching.verify(&index));
    let critical = matching.critical.iter().map(Vec::len).collect::<Vec<_>>();
    if !select(&critical) {
        return Ok(None);
    }
    Ok(Some(morse_boundaries(&index, &matching, crate::Z)?))
}

#[cfg(test)]
pub(super) fn critical_cell_counts(complex: &SimplicialComplex) -> Vec<usize> {
    let index = MorseIndex::build(complex);
    build_matching(&index)
        .critical
        .iter()
        .map(Vec::len)
        .collect()
}

fn build_matching(index: &MorseIndex) -> MorseMatching {
    let mut alive = vec![true; index.cells];
    let mut live_cofaces = index.cofaces.iter().map(Vec::len).collect::<Vec<_>>();
    let mut up = vec![None; index.cells];
    let mut down = vec![None; index.cells];
    let mut critical = vec![Vec::new(); index.offset.len().saturating_sub(1)];
    let mut removal_order = vec![usize::MAX; index.cells];
    let mut free = BinaryHeap::new();
    for (cell, &count) in live_cofaces.iter().enumerate() {
        if count == 1 {
            free.push(cell);
        }
    }
    let mut next_order = 0usize;
    let mut remaining = index.cells;

    while remaining > 0 {
        let mut collapsed = false;
        while let Some(face) = free.pop() {
            if !alive[face] || live_cofaces[face] != 1 {
                continue;
            }
            let Some(coface) = index.cofaces[face]
                .iter()
                .copied()
                .find(|&candidate| alive[candidate])
            else {
                continue;
            };
            up[face] = Some(coface);
            down[coface] = Some(face);
            drop_cell(
                face,
                index,
                &mut alive,
                &mut live_cofaces,
                &mut free,
                &mut removal_order,
                &mut next_order,
            );
            drop_cell(
                coface,
                index,
                &mut alive,
                &mut live_cofaces,
                &mut free,
                &mut removal_order,
                &mut next_order,
            );
            remaining -= 2;
            collapsed = true;
        }
        if collapsed {
            continue;
        }

        let cell = (0..index.cells)
            .filter(|&candidate| alive[candidate])
            .max_by_key(|&candidate| (index.dimension[candidate], Reverse(candidate)))
            .expect("a positive remaining count has an alive Morse cell");
        critical[index.dimension[cell]].push(cell);
        drop_cell(
            cell,
            index,
            &mut alive,
            &mut live_cofaces,
            &mut free,
            &mut removal_order,
            &mut next_order,
        );
        remaining -= 1;
    }
    for cells in &mut critical {
        cells.sort_unstable();
    }
    MorseMatching {
        critical,
        up,
        down,
        removal_order,
    }
}

#[allow(clippy::too_many_arguments)]
fn drop_cell(
    cell: usize,
    index: &MorseIndex,
    alive: &mut [bool],
    live_cofaces: &mut [usize],
    free: &mut BinaryHeap<usize>,
    removal_order: &mut [usize],
    next_order: &mut usize,
) {
    alive[cell] = false;
    removal_order[cell] = *next_order;
    *next_order += 1;
    for &(face, _) in &index.faces[cell] {
        if alive[face] {
            live_cofaces[face] -= 1;
            if live_cofaces[face] == 1 {
                free.push(face);
            }
        }
    }
}

fn morse_boundaries<R: Ring>(
    index: &MorseIndex,
    matching: &MorseMatching,
    ring: R,
) -> Result<BTreeMap<i32, SparseMatrix<R>>, TopologyError> {
    let top = matching.critical.len().saturating_sub(1);
    let mut boundaries = BTreeMap::new();
    if matching.critical.is_empty() {
        return Ok(boundaries);
    }
    if top == 0 {
        boundaries.insert(0, SparseMatrix::zeros(ring, 0, matching.critical[0].len()));
        return Ok(boundaries);
    }

    let zero = ring.zero();
    let one = ring.one();
    let negative_one = ring.neg(&one)?;
    for dimension in 1..=top {
        let mut critical_row = vec![usize::MAX; index.cells];
        for (row, &cell) in matching.critical[dimension - 1].iter().enumerate() {
            critical_row[cell] = row;
        }
        let mut entries = Vec::new();
        for (column, &cell) in matching.critical[dimension].iter().enumerate() {
            let mut coefficients = vec![zero.clone(); index.cells];
            let mut pending = BinaryHeap::new();
            for &(face, positive) in &index.faces[cell] {
                add_pending(
                    &ring,
                    &mut coefficients,
                    &mut pending,
                    matching.removal_order[face],
                    face,
                    if positive { &one } else { &negative_one },
                )?;
            }
            while let Some(Reverse((_order, face))) = pending.pop() {
                let coefficient = core::mem::replace(&mut coefficients[face], zero.clone());
                if coefficient == zero {
                    continue;
                }
                let row = critical_row[face];
                if row != usize::MAX {
                    entries.push((row, column, coefficient));
                    continue;
                }
                let Some(coface) = matching.up[face] else {
                    debug_assert!(matching.down[face].is_some());
                    continue;
                };
                let pivot_positive = index.faces[coface]
                    .iter()
                    .find_map(|&(candidate, positive)| (candidate == face).then_some(positive))
                    .expect("a Morse pair is incident");
                for &(other_face, other_positive) in &index.faces[coface] {
                    if other_face == face {
                        continue;
                    }
                    debug_assert!(
                        matching.removal_order[other_face] > matching.removal_order[face]
                    );
                    let contribution = if pivot_positive != other_positive {
                        coefficient.clone()
                    } else {
                        ring.neg(&coefficient)?
                    };
                    add_pending(
                        &ring,
                        &mut coefficients,
                        &mut pending,
                        matching.removal_order[other_face],
                        other_face,
                        &contribution,
                    )?;
                }
            }
        }
        let degree =
            i32::try_from(dimension).map_err(|_| TopologyError::DimensionTooLarge { dimension })?;
        boundaries.insert(
            degree,
            SparseMatrix::from_triplets(
                ring.clone(),
                matching.critical[dimension - 1].len(),
                matching.critical[dimension].len(),
                entries,
            )?,
        );
    }
    Ok(boundaries)
}

fn add_pending<R: Ring>(
    ring: &R,
    coefficients: &mut [R::Element],
    pending: &mut BinaryHeap<Reverse<(usize, usize)>>,
    order: usize,
    cell: usize,
    contribution: &R::Element,
) -> Result<(), TopologyError> {
    let zero = ring.zero();
    let was_zero = coefficients[cell] == zero;
    coefficients[cell] = ring.add(&coefficients[cell], contribution)?;
    if was_zero && coefficients[cell] != zero {
        pending.push(Reverse((order, cell)));
    }
    Ok(())
}

fn dense_chain_complex<R: Ring>(
    ring: R,
    boundaries: &BTreeMap<i32, SparseMatrix<R>>,
) -> Result<ChainComplex<R>, TopologyError> {
    Ok(ChainComplex::from_boundaries(
        ring,
        boundaries
            .iter()
            .map(|(&degree, boundary)| (degree, boundary.to_dense()))
            .collect::<BTreeMap<i32, Matrix<R>>>(),
    )?)
}
