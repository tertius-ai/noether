/// The canonical Python context for the ring of integers.
#[pyclass(module = "noether", name = "IntegerRing", frozen, from_py_object)]
#[derive(Clone, Copy)]
pub struct PyIntegerRing;

#[pymethods]
impl PyIntegerRing {
    /// Versioned language-neutral semantic identity.
    #[classattr]
    fn type_id() -> &'static str {
        IntegerRing::TYPE_ID
    }

    #[new]
    fn new() -> Self {
        Self
    }

    fn zero(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        integer_to_python(py, &Integer::zero())
    }

    fn one(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        integer_to_python(py, &Integer::one())
    }

    /// Construct the canonical principal ideal generated by integers.
    fn ideal(&self, generators: &Bound<'_, PyAny>) -> PyResult<PyIdeal> {
        let generators = generators
            .try_iter()
            .map_err(|_| {
                pyo3::exceptions::PyTypeError::new_err("ideal generators must be iterable")
            })?
            .map(|value| extract_integer(&value?))
            .collect::<PyResult<Vec<_>>>()?;
        Ok(PyIdeal::from_integer(IntegerRing.ideal(generators)))
    }

    fn __call__(&self, py: Python<'_>, value: &Bound<'_, PyAny>) -> PyResult<Py<PyAny>> {
        integer_to_python(py, &extract_integer(value)?)
    }

    /// Return the nonnegative greatest common divisor.
    fn gcd(
        &self,
        py: Python<'_>,
        left: &Bound<'_, PyAny>,
        right: &Bound<'_, PyAny>,
    ) -> PyResult<Py<PyAny>> {
        let gcd = IntegerRing.gcd(&extract_integer(left)?, &extract_integer(right)?);
        integer_to_python(py, &gcd)
    }

    /// Return a normalized Bézout witness for two integers.
    fn extended_gcd(
        &self,
        left: &Bound<'_, PyAny>,
        right: &Bound<'_, PyAny>,
    ) -> PyResult<PyBezoutIdentity> {
        Ok(PyBezoutIdentity {
            inner: BezoutIdentityInner::Integer(
                IntegerRing.extended_gcd(&extract_integer(left)?, &extract_integer(right)?),
            ),
        })
    }

    /// Return the canonical unital embedding `Z -> Q`.
    fn rational_embedding(&self) -> PyIntegerRationalEmbedding {
        PyIntegerRationalEmbedding {
            inner: IntegerRing.rational_embedding(),
        }
    }

    /// Return canonical reduction into one explicit residue ring.
    fn reduction(&self, target: &PyResidueRing) -> PyIntegerReduction {
        PyIntegerReduction {
            inner: IntegerRing.reduction(&target.inner),
        }
    }

    /// Return the canonical unital map into one explicit finite field.
    fn finite_field_map(&self, target: &PyFiniteField) -> PyIntegerFiniteFieldMap {
        PyIntegerFiniteFieldMap {
            inner: IntegerRing.finite_field_map(&target.inner),
        }
    }

    /// Serialize the singleton integer-ring context as canonical typed JSON.
    fn to_json(&self) -> PyResult<String> {
        IntegerRing.to_json().map_err(serialization_error)
    }

    /// Deserialize and validate the singleton integer-ring context.
    #[classmethod]
    fn from_json(_cls: &Bound<'_, PyType>, value: &str) -> PyResult<Self> {
        IntegerRing::from_json(value).map_err(serialization_error)?;
        Ok(Self)
    }

    fn __repr__(&self) -> &'static str {
        "Z"
    }

    fn __str__(&self) -> &'static str {
        "Z"
    }

    fn __hash__(&self) -> isize {
        0x5a
    }

    fn __eq__(&self, _other: &Self) -> bool {
        true
    }
}

/// The canonical Python context for the field of rational numbers.
#[pyclass(module = "noether", name = "RationalField", frozen, from_py_object)]
#[derive(Clone, Copy)]
pub struct PyRationalField;

#[pymethods]
impl PyRationalField {
    /// Versioned language-neutral semantic identity.
    #[classattr]
    fn type_id() -> &'static str {
        RationalField::TYPE_ID
    }

    #[new]
    fn new() -> Self {
        Self
    }

    fn zero(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        rational_to_python(py, &Rational::zero())
    }

    fn one(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        rational_to_python(py, &Rational::one())
    }

    fn __call__(&self, py: Python<'_>, value: &Bound<'_, PyAny>) -> PyResult<Py<PyAny>> {
        rational_to_python(py, &extract_rational(py, value)?)
    }

    fn inverse(&self, py: Python<'_>, value: &Bound<'_, PyAny>) -> PyResult<Py<PyAny>> {
        let inverse = extract_rational(py, value)?
            .inverse()
            .map_err(|error| pyo3::exceptions::PyZeroDivisionError::new_err(error.to_string()))?;
        rational_to_python(py, &inverse)
    }

    /// Return the canonical field gcd: zero only for the pair `(0, 0)`.
    fn gcd(
        &self,
        py: Python<'_>,
        left: &Bound<'_, PyAny>,
        right: &Bound<'_, PyAny>,
    ) -> PyResult<Py<PyAny>> {
        let gcd = RationalField.gcd(&extract_rational(py, left)?, &extract_rational(py, right)?);
        rational_to_python(py, &gcd)
    }

    /// Return a canonical Bézout witness for two rational numbers.
    fn extended_gcd(
        &self,
        py: Python<'_>,
        left: &Bound<'_, PyAny>,
        right: &Bound<'_, PyAny>,
    ) -> PyResult<PyBezoutIdentity> {
        Ok(PyBezoutIdentity {
            inner: BezoutIdentityInner::Rational(
                RationalField
                    .extended_gcd(&extract_rational(py, left)?, &extract_rational(py, right)?),
            ),
        })
    }

    /// Serialize the singleton rational-field context as canonical typed JSON.
    fn to_json(&self) -> PyResult<String> {
        RationalField.to_json().map_err(serialization_error)
    }

    /// Deserialize and validate the singleton rational-field context.
    #[classmethod]
    fn from_json(_cls: &Bound<'_, PyType>, value: &str) -> PyResult<Self> {
        RationalField::from_json(value).map_err(serialization_error)?;
        Ok(Self)
    }

    fn __repr__(&self) -> &'static str {
        "Q"
    }

    fn __str__(&self) -> &'static str {
        "Q"
    }

    fn __hash__(&self) -> isize {
        0x51
    }

    fn __eq__(&self, _other: &Self) -> bool {
        true
    }
}

#[derive(Clone, PartialEq, Eq)]
enum BezoutIdentityInner {
    Integer(BezoutIdentity<IntegerRing>),
    Rational(BezoutIdentity<RationalField>),
}

/// A typed extended-gcd result with a directly checkable identity.
#[pyclass(module = "noether", name = "BezoutIdentity", frozen, from_py_object)]
#[derive(Clone, PartialEq, Eq)]
pub struct PyBezoutIdentity {
    inner: BezoutIdentityInner,
}

fn bounded_component(mut rendered: String) -> String {
    const CHARACTER_LIMIT: usize = 64;
    if rendered.len() > CHARACTER_LIMIT {
        rendered.truncate(CHARACTER_LIMIT);
        rendered.push_str("...");
    }
    rendered
}

fn serialization_error(error: impl ToString) -> PyErr {
    super::errors::noether_error(NoetherError::Serialization(error.to_string()))
}

#[pymethods]
impl PyBezoutIdentity {
    /// Versioned language-neutral semantic identity.
    #[classattr]
    fn type_id() -> &'static str {
        BezoutIdentity::<IntegerRing>::TYPE_ID
    }

    /// Coefficient context in which the identity is stated.
    #[getter]
    fn ring(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        match self.inner {
            BezoutIdentityInner::Integer(_) => Ok(Py::new(py, PyIntegerRing)?.into_any()),
            BezoutIdentityInner::Rational(_) => Ok(Py::new(py, PyRationalField)?.into_any()),
        }
    }

    /// Canonically normalized greatest common divisor.
    #[getter]
    fn gcd(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        match &self.inner {
            BezoutIdentityInner::Integer(identity) => integer_to_python(py, &identity.gcd),
            BezoutIdentityInner::Rational(identity) => rational_to_python(py, &identity.gcd),
        }
    }

    /// Coefficient multiplying the first input.
    #[getter]
    fn coefficient_a(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        match &self.inner {
            BezoutIdentityInner::Integer(identity) => {
                integer_to_python(py, &identity.coefficient_a)
            }
            BezoutIdentityInner::Rational(identity) => {
                rational_to_python(py, &identity.coefficient_a)
            }
        }
    }

    /// Coefficient multiplying the second input.
    #[getter]
    fn coefficient_b(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        match &self.inner {
            BezoutIdentityInner::Integer(identity) => {
                integer_to_python(py, &identity.coefficient_b)
            }
            BezoutIdentityInner::Rational(identity) => {
                rational_to_python(py, &identity.coefficient_b)
            }
        }
    }

    /// Verify the normalized gcd and Bézout relation against the two inputs.
    fn verify(
        &self,
        py: Python<'_>,
        ring: &Bound<'_, PyAny>,
        left: &Bound<'_, PyAny>,
        right: &Bound<'_, PyAny>,
    ) -> PyResult<()> {
        match &self.inner {
            BezoutIdentityInner::Integer(identity) => {
                if !ring.is_instance_of::<PyIntegerRing>() {
                    return Err(super::errors::context_mismatch(ContextMismatchError {
                        expected: IntegerRing::TYPE_ID.to_owned(),
                        actual: "a non-integer coefficient context".to_owned(),
                    }));
                }
                identity
                    .verify(
                        &IntegerRing,
                        &extract_integer(left)?,
                        &extract_integer(right)?,
                    )
                    .map_err(super::errors::verification)
            }
            BezoutIdentityInner::Rational(identity) => {
                if !ring.is_instance_of::<PyRationalField>() {
                    return Err(super::errors::context_mismatch(ContextMismatchError {
                        expected: RationalField::TYPE_ID.to_owned(),
                        actual: "a non-rational coefficient context".to_owned(),
                    }));
                }
                identity
                    .verify(
                        &RationalField,
                        &extract_rational(py, left)?,
                        &extract_rational(py, right)?,
                    )
                    .map_err(super::errors::verification)
            }
        }
    }

    /// Canonical JSON representation shared with the Rust facade.
    fn to_json(&self) -> PyResult<String> {
        match &self.inner {
            BezoutIdentityInner::Integer(identity) => {
                identity.to_json().map_err(super::errors::noether_error)
            }
            BezoutIdentityInner::Rational(identity) => {
                identity.to_json().map_err(super::errors::noether_error)
            }
        }
    }

    /// Restore a witness with a checked semantic and coefficient-context ID.
    #[classmethod]
    fn from_json(_cls: &Bound<'_, PyType>, value: &str) -> PyResult<Self> {
        let parsed =
            serde_json::from_str::<serde_json::Value>(value).map_err(serialization_error)?;
        let ring = parsed
            .get("ring")
            .and_then(serde_json::Value::as_str)
            .ok_or_else(|| serialization_error("Bézout JSON has no string ring identifier"))?;
        let inner = match ring {
            IntegerRing::TYPE_ID => BezoutIdentityInner::Integer(
                BezoutIdentity::<IntegerRing>::from_json(value)
                    .map_err(super::errors::noether_error)?,
            ),
            RationalField::TYPE_ID => BezoutIdentityInner::Rational(
                BezoutIdentity::<RationalField>::from_json(value)
                    .map_err(super::errors::noether_error)?,
            ),
            _ => {
                return Err(serialization_error(format!(
                    "unsupported Bézout coefficient context {ring}"
                )));
            }
        };
        Ok(Self { inner })
    }

    fn _tertius_summary_(&self, py: Python<'_>) -> PyResult<Py<PyAny>> {
        let summary = PyDict::new(py);
        summary.set_item("type", Self::type_id())?;
        summary.set_item(
            "ring",
            match self.inner {
                BezoutIdentityInner::Integer(_) => "Z",
                BezoutIdentityInner::Rational(_) => "Q",
            },
        )?;
        summary.set_item("gcd", self.gcd(py)?)?;
        Ok(summary.unbind().into_any())
    }

    fn __eq__(&self, other: &Self) -> bool {
        self == other
    }

    fn __repr__(&self) -> String {
        crate::py::repr::bounded_text({
            let (ring, gcd, coefficient_a, coefficient_b) = match &self.inner {
                BezoutIdentityInner::Integer(identity) => (
                    "Z",
                    identity.gcd.to_string(),
                    identity.coefficient_a.to_string(),
                    identity.coefficient_b.to_string(),
                ),
                BezoutIdentityInner::Rational(identity) => (
                    "Q",
                    identity.gcd.to_string(),
                    identity.coefficient_a.to_string(),
                    identity.coefficient_b.to_string(),
                ),
            };
            format!(
                "BezoutIdentity(ring={ring}, gcd={}, coefficient_a={}, coefficient_b={})",
                bounded_component(gcd),
                bounded_component(coefficient_a),
                bounded_component(coefficient_b)
            )
        })
    }

    fn __str__(&self) -> String {
        match &self.inner {
            BezoutIdentityInner::Integer(identity) => identity.to_string(),
            BezoutIdentityInner::Rational(identity) => identity.to_string(),
        }
    }
}
