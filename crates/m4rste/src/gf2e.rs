//! GF(2^e) field arithmetic from a minimal-polynomial bit pattern.
//!
//! Elements are polynomials over F_2 of degree `< e`, stored in the low
//! `e` bits of a `u16`. [`Gf2e`] is the lightweight `Copy` field
//! descriptor; its `mul` / `inv` are carry-less (used to *build* the
//! tables and as a reference oracle). [`Gf2eTables`] is the fast path:
//! discrete-log / antilog tables turning a field multiply into two
//! lookups and an add. `Mzed::echelonize` builds a `Gf2eTables` once
//! per call; `matmul` doesn't touch field arithmetic at all (it goes
//! through the bit-sliced F_2 path in `crate::matmul`).

/// A GF(2^e) field context: the minimal polynomial plus its degree.
///
/// `Copy` and tiny — pass it by value. Two `Mzed` matrices can only be
/// combined when their `Gf2e` contexts are equal.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Gf2e {
    /// Minimal polynomial as a bit pattern, degree-`e` term included.
    minpoly: u64,
    /// Extension degree `e` (so the field has `2^e` elements).
    e: u32,
}

impl Gf2e {
    /// Build a field context from a minimal polynomial bit pattern.
    ///
    /// # Panics
    ///
    /// Panics if `minpoly` has degree `< 1` or `> 16` (this crate is
    /// scoped to `e <= 16`, one `u16` per element). Irreducibility is
    /// **not** checked — passing a reducible polynomial yields a ring,
    /// not a field, and the `inv` path will misbehave; callers are
    /// trusted to pass a genuine minimal polynomial (the engine sources
    /// these from FLINT's Conway-polynomial tables).
    pub fn new(minpoly: u64) -> Self {
        assert!(minpoly >= 2, "Gf2e::new: minpoly must have degree >= 1");
        let e = 63 - minpoly.leading_zeros();
        assert!(
            (1..=16).contains(&e),
            "Gf2e::new: extension degree {e} out of range (1..=16)"
        );
        Self { minpoly, e }
    }

    /// Extension degree `e`.
    pub fn degree(&self) -> u32 {
        self.e
    }

    /// Number of field elements, `2^e`.
    pub fn order(&self) -> u64 {
        1u64 << self.e
    }

    /// The raw minimal-polynomial bit pattern.
    pub fn minpoly(&self) -> u64 {
        self.minpoly
    }

    /// Field addition — XOR of the polynomial representations.
    #[inline]
    pub fn add(&self, a: u16, b: u16) -> u16 {
        a ^ b
    }

    /// Field multiplication: carry-less polynomial product reduced
    /// modulo the minimal polynomial.
    #[inline]
    pub fn mul(&self, a: u16, b: u16) -> u16 {
        let mut acc: u32 = 0;
        let mut aa = a as u32;
        let mut bb = b as u32;
        while bb != 0 {
            if bb & 1 != 0 {
                acc ^= aa;
            }
            bb >>= 1;
            aa <<= 1;
        }
        self.reduce(acc)
    }

    /// Reduce a `< 2e`-bit carry-less product modulo `minpoly`.
    #[inline]
    fn reduce(&self, mut acc: u32) -> u16 {
        let mp = self.minpoly as u32;
        while acc != 0 {
            let hb = 31 - acc.leading_zeros();
            if hb < self.e {
                break;
            }
            acc ^= mp << (hb - self.e);
        }
        acc as u16
    }

    /// `a^n` in the field, by square-and-multiply.
    pub fn pow(&self, a: u16, mut n: u64) -> u16 {
        let mut base = a;
        let mut result: u16 = 1;
        while n != 0 {
            if n & 1 != 0 {
                result = self.mul(result, base);
            }
            base = self.mul(base, base);
            n >>= 1;
        }
        result
    }

    /// Multiplicative inverse of a nonzero element.
    ///
    /// Uses Fermat's little theorem: `a^(2^e - 2) = a^{-1}` in
    /// GF(2^e)*. This is the carry-less reference; the hot path uses
    /// [`Gf2eTables::inv`].
    ///
    /// # Panics
    ///
    /// Panics if `a == 0`.
    pub fn inv(&self, a: u16) -> u16 {
        assert!(a != 0, "Gf2e::inv: zero has no inverse");
        self.pow(a, self.order() - 2)
    }

    /// Build the discrete-log / antilog tables for this field.
    ///
    /// O(2^e) work — call once and reuse (`Mzed::echelonize` builds one
    /// per call and amortises it over the O(n^3) elimination). Searches
    /// for a multiplicative generator: `x` itself is a generator only
    /// when the minimal polynomial is *primitive* (it is for GF(4) /
    /// GF(16) with the usual polys, but not for the AES GF(256) poly
    /// `0x11B`, where the smallest generator is `3`).
    pub fn tables(&self) -> Gf2eTables {
        let order = ((1u32 << self.e) - 1) as usize; // |GF(2^e)*|
        let field_size = 1usize << self.e;
        for g in 2u16..(field_size as u16) {
            // Walk the cyclic subgroup generated by `g`; if it visits
            // all `order` nonzero elements without repeating, `g` is a
            // generator.
            let mut antilog = vec![0u16; 2 * order];
            let mut seen = vec![false; field_size];
            let mut pow: u16 = 1;
            let mut is_gen = true;
            for slot in antilog.iter_mut().take(order) {
                if seen[pow as usize] {
                    is_gen = false;
                    break;
                }
                seen[pow as usize] = true;
                *slot = pow;
                pow = self.mul(pow, g);
            }
            if !is_gen {
                continue;
            }
            // Double the antilog so `mul` never needs a mod: a log sum
            // is at most `2*(order-1) < 2*order`.
            for i in 0..order {
                antilog[order + i] = antilog[i];
            }
            let mut log = vec![0u16; field_size];
            for (i, &a) in antilog.iter().take(order).enumerate() {
                log[a as usize] = i as u16;
            }
            return Gf2eTables {
                order: order as u16,
                log,
                antilog,
            };
        }
        unreachable!("every finite field GF(2^e)* is cyclic — a generator exists")
    }
}

/// Discrete-log / antilog tables for a fixed GF(2^e) — the fast field
/// arithmetic path.
///
/// Built by [`Gf2e::tables`]. A multiply is `antilog[log[a] + log[b]]`
/// (the antilog table is doubled so the log sum never needs a mod); an
/// inverse is `antilog[order - log[a]]`.
#[derive(Debug, Clone)]
pub struct Gf2eTables {
    /// `|GF(2^e)*| = 2^e - 1`.
    order: u16,
    /// `log[a]` = discrete log of `a` base the chosen generator
    /// (`log[0]` is unused).
    log: Vec<u16>,
    /// `antilog[i]` = generator^i, length `2 * order` (doubled).
    antilog: Vec<u16>,
}

impl Gf2eTables {
    /// Field multiplication via table lookup.
    #[inline]
    pub fn mul(&self, a: u16, b: u16) -> u16 {
        if a == 0 || b == 0 {
            0
        } else {
            // log[a] + log[b] <= 2*(order-1) < 2*order — in range.
            self.antilog[self.log[a as usize] as usize + self.log[b as usize] as usize]
        }
    }

    /// Multiplicative inverse of a nonzero element via table lookup.
    ///
    /// # Panics
    ///
    /// Panics if `a == 0`.
    #[inline]
    pub fn inv(&self, a: u16) -> u16 {
        debug_assert!(a != 0, "Gf2eTables::inv: zero has no inverse");
        // a^{-1} = generator^{order - log[a]}.
        self.antilog[self.order as usize - self.log[a as usize] as usize]
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn gf4_basics() {
        let f = Gf2e::new(0b111); // x^2 + x + 1
        assert_eq!(f.degree(), 2);
        assert_eq!(f.order(), 4);
        // x * x = x + 1 (since x^2 = x + 1 mod minpoly). x = 0b10 = 2,
        // x + 1 = 0b11 = 3.
        assert_eq!(f.mul(2, 2), 3);
        // x * (x + 1) = x^2 + x = (x + 1) + x = 1.
        assert_eq!(f.mul(2, 3), 1);
        // every nonzero element times its inverse is 1.
        for a in 1u16..4 {
            assert_eq!(f.mul(a, f.inv(a)), 1, "inv failed for {a}");
        }
    }

    #[test]
    fn gf256_inverse_roundtrip() {
        let f = Gf2e::new(0x11B); // AES polynomial
        assert_eq!(f.degree(), 8);
        for a in 1u16..256 {
            assert_eq!(f.mul(a, f.inv(a)), 1, "inv failed for {a}");
        }
    }

    #[test]
    fn add_is_xor() {
        let f = Gf2e::new(0x11B);
        assert_eq!(f.add(0xAB, 0xCD), 0xAB ^ 0xCD);
        // characteristic 2: a + a = 0.
        for a in 0u16..256 {
            assert_eq!(f.add(a, a), 0);
        }
    }

    #[test]
    fn tables_mul_inv_match_carryless_exhaustively() {
        // GF(4), GF(8), GF(16), GF(32), GF(256) — note 0x11B (AES) is
        // not primitive, so the generator search must kick in.
        for &minpoly in &[0b111u64, 0b1011, 0b1_0011, 0b10_0101, 0x11B] {
            let f = Gf2e::new(minpoly);
            let t = f.tables();
            let n = 1u16 << f.degree();
            for a in 0..n {
                for b in 0..n {
                    assert_eq!(
                        t.mul(a, b),
                        f.mul(a, b),
                        "table mul != carryless for minpoly={minpoly:#x} a={a} b={b}"
                    );
                }
                if a != 0 {
                    assert_eq!(
                        t.inv(a),
                        f.inv(a),
                        "table inv != carryless for minpoly={minpoly:#x} a={a}"
                    );
                    assert_eq!(t.mul(a, t.inv(a)), 1);
                }
            }
        }
    }
}
