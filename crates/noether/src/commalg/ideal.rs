//! Canonical ideals and checked prime ideals of commutative rings.

use core::fmt;

use serde::ser::SerializeStruct;
use serde::{Deserialize, Deserializer, Serialize, Serializer};

use crate::{
    CommutativeRing, ContextMismatchError, Integer, IntegerRing, NoetherError, SemanticType,
    TypeDescription,
};

static IDEAL_DESCRIPTION: TypeDescription = TypeDescription {
    semantic_id: "noether/commalg/Ideal@1",
    rust_path: "noether::commalg::Ideal",
    python_path: Some("noether.commalg.Ideal"),
};

static PRIME_IDEAL_DESCRIPTION: TypeDescription = TypeDescription {
    semantic_id: "noether/commalg/PrimeIdeal@1",
    rust_path: "noether::commalg::PrimeIdeal",
    python_path: Some("noether.commalg.PrimeIdeal"),
};

/// Failure to establish a canonical ideal value.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum IdealError {
    /// A generator did not belong to the coefficient ring.
    ContextMismatch(ContextMismatchError),
}

impl fmt::Display for IdealError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Self::ContextMismatch(error) => error.fmt(f),
        }
    }
}

impl std::error::Error for IdealError {
    fn source(&self) -> Option<&(dyn std::error::Error + 'static)> {
        match self {
            Self::ContextMismatch(error) => Some(error),
        }
    }
}

/// An ideal of one explicit commutative-ring context.
///
/// The stored generators are a backend-independent *canonical* generating
/// family, not necessarily the generators supplied by a caller. Polynomial
/// rings can use a reduced Groebner basis while number-field orders use a
/// row-Hermite lattice basis. This lets equality remain ideal equality without
/// baking either representation into the shared type.
#[derive(Clone)]
pub struct Ideal<R: CommutativeRing> {
    ring: R,
    canonical_generators: Vec<R::Element>,
}

impl<R: CommutativeRing> Ideal<R> {
    /// The coefficient ring of this ideal.
    pub fn ring(&self) -> &R {
        &self.ring
    }

    /// A canonical generating family for this ideal.
    pub fn generators(&self) -> &[R::Element] {
        &self.canonical_generators
    }

    pub(crate) fn from_canonical_generators(
        ring: R,
        canonical_generators: Vec<R::Element>,
    ) -> Result<Self, IdealError> {
        if canonical_generators
            .iter()
            .any(|generator| !ring.contains(generator))
        {
            return Err(IdealError::ContextMismatch(ContextMismatchError {
                expected: R::TYPE_ID.to_owned(),
                actual: "ideal generator from another context".to_owned(),
            }));
        }
        Ok(Self {
            ring,
            canonical_generators,
        })
    }
}

impl IntegerRing {
    /// Construct the canonical principal ideal generated by the supplied
    /// integers. The empty family and an all-zero family both give `(0)`.
    pub fn ideal<I>(&self, generators: I) -> Ideal<IntegerRing>
    where
        I: IntoIterator<Item = Integer>,
    {
        let generator = generators
            .into_iter()
            .fold(Integer::zero(), |gcd, value| gcd.gcd(&value));
        let canonical_generators = if generator.is_zero() {
            Vec::new()
        } else {
            vec![generator.abs()]
        };
        Ideal {
            ring: *self,
            canonical_generators,
        }
    }
}

impl Ideal<IntegerRing> {
    /// Unique nonnegative generator of this principal ideal.
    pub fn principal_generator(&self) -> Integer {
        self.generators()
            .first()
            .cloned()
            .unwrap_or_else(Integer::zero)
    }

    /// Decide divisibility membership in this principal ideal.
    pub fn contains(&self, value: &Integer) -> bool {
        let generator = self.principal_generator();
        if generator.is_zero() {
            value.is_zero()
        } else {
            (value % &generator).is_zero()
        }
    }

    /// Sum of principal ideals, whose positive generator is a gcd.
    pub fn sum(&self, other: &Self) -> Self {
        IntegerRing.ideal([self.principal_generator(), other.principal_generator()])
    }

    /// Product of principal ideals.
    pub fn product(&self, other: &Self) -> Self {
        IntegerRing.ideal([&self.principal_generator() * &other.principal_generator()])
    }

    /// Nonnegative power of this principal ideal, with exponent zero equal to `(1)`.
    pub fn pow(&self, exponent: u64) -> Self {
        if exponent == 0 {
            IntegerRing.ideal([Integer::one()])
        } else {
            IntegerRing.ideal([self.principal_generator().pow(exponent)])
        }
    }

    /// Recheck the unique nonnegative-generator convention.
    pub fn verify(&self) -> Result<(), IdealError> {
        if self.ring != IntegerRing
            || self.generators().len() > 1
            || self
                .generators()
                .first()
                .is_some_and(|generator| !generator.is_positive())
        {
            return Err(IdealError::ContextMismatch(ContextMismatchError {
                expected: "canonical nonnegative principal ideal of Z".to_owned(),
                actual: "noncanonical integer ideal".to_owned(),
            }));
        }
        Ok(())
    }

    /// Serialize the canonical principal ideal as typed JSON.
    pub fn to_json(&self) -> Result<String, NoetherError> {
        serde_json::to_string(self).map_err(|error| NoetherError::Serialization(error.to_string()))
    }

    /// Deserialize and revalidate a canonical principal ideal.
    pub fn from_json(value: &str) -> Result<Self, NoetherError> {
        serde_json::from_str(value).map_err(|error| NoetherError::Serialization(error.to_string()))
    }
}

impl Serialize for Ideal<IntegerRing> {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: Serializer,
    {
        let mut state = serializer.serialize_struct("Ideal", 3)?;
        state.serialize_field("type", Self::TYPE_ID)?;
        state.serialize_field("ring", &self.ring)?;
        state.serialize_field("generators", &self.canonical_generators)?;
        state.end()
    }
}

#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct IntegerIdealWire {
    #[serde(rename = "type")]
    type_id: String,
    ring: IntegerRing,
    generators: Vec<Integer>,
}

impl<'de> Deserialize<'de> for Ideal<IntegerRing> {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: Deserializer<'de>,
    {
        let wire = IntegerIdealWire::deserialize(deserializer)?;
        if wire.type_id != Self::TYPE_ID {
            return Err(serde::de::Error::custom(format!(
                "expected type {}, received {}",
                Self::TYPE_ID,
                wire.type_id
            )));
        }
        if wire.ring != IntegerRing {
            return Err(serde::de::Error::custom("integer ideal has the wrong ring"));
        }
        let supplied = wire.generators;
        let ideal = IntegerRing.ideal(supplied.iter().cloned());
        if ideal.generators() != supplied {
            return Err(serde::de::Error::custom(
                "integer ideal does not use its canonical positive generator",
            ));
        }
        Ok(ideal)
    }
}

impl<R: CommutativeRing> PartialEq for Ideal<R> {
    fn eq(&self, other: &Self) -> bool {
        self.ring == other.ring && self.canonical_generators == other.canonical_generators
    }
}

impl<R: CommutativeRing> Eq for Ideal<R> {}

impl<R: CommutativeRing> fmt::Debug for Ideal<R> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("Ideal")
            .field("ring", &R::TYPE_ID)
            .field("generators", &self.canonical_generators.len())
            .finish()
    }
}

impl<R: CommutativeRing> fmt::Display for Ideal<R> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(
            f,
            "Ideal(ring={}, generators={})",
            R::TYPE_ID,
            self.canonical_generators.len()
        )
    }
}

impl<R: CommutativeRing> SemanticType for Ideal<R> {
    const TYPE_ID: &'static str = "noether/commalg/Ideal@1";

    fn canonical_bytes(&self) -> Result<Vec<u8>, NoetherError> {
        let mut output = Vec::new();
        append_component(&mut output, &self.ring.canonical_bytes()?)?;
        for generator in &self.canonical_generators {
            append_component(&mut output, &generator.canonical_bytes()?)?;
        }
        Ok(output)
    }

    fn describe() -> &'static TypeDescription {
        &IDEAL_DESCRIPTION
    }
}

/// A checked prime ideal of one explicit commutative-ring context.
///
/// Equality and semantic identity depend on the canonical ideal, not on the
/// particular witness used to establish primality.
#[derive(Clone)]
pub struct PrimeIdeal<R: CommutativeRing> {
    ideal: Ideal<R>,
    witness: Vec<u8>,
}

impl<R: CommutativeRing> PrimeIdeal<R> {
    /// The canonical ideal certified as prime.
    pub fn ideal(&self) -> &Ideal<R> {
        &self.ideal
    }

    pub(crate) fn from_verified_parts(ideal: Ideal<R>, witness: Vec<u8>) -> Self {
        Self { ideal, witness }
    }

    pub(crate) fn witness(&self) -> &[u8] {
        &self.witness
    }
}

impl<R: CommutativeRing> PartialEq for PrimeIdeal<R> {
    fn eq(&self, other: &Self) -> bool {
        self.ideal == other.ideal
    }
}

impl<R: CommutativeRing> Eq for PrimeIdeal<R> {}

impl<R: CommutativeRing> fmt::Debug for PrimeIdeal<R> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_tuple("PrimeIdeal").field(&self.ideal).finish()
    }
}

impl<R: CommutativeRing> fmt::Display for PrimeIdeal<R> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "PrimeIdeal({})", self.ideal)
    }
}

impl<R: CommutativeRing> SemanticType for PrimeIdeal<R> {
    const TYPE_ID: &'static str = "noether/commalg/PrimeIdeal@1";

    fn canonical_bytes(&self) -> Result<Vec<u8>, NoetherError> {
        self.ideal.canonical_bytes()
    }

    fn describe() -> &'static TypeDescription {
        &PRIME_IDEAL_DESCRIPTION
    }
}

fn append_component(output: &mut Vec<u8>, component: &[u8]) -> Result<(), NoetherError> {
    let length = u64::try_from(component.len()).map_err(|_| {
        NoetherError::Serialization("ideal component does not fit canonical framing".to_owned())
    })?;
    output.extend_from_slice(&length.to_be_bytes());
    output.extend_from_slice(component);
    Ok(())
}
