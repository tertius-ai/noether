//! Normal closure, derived & lower-central series, solvability / nilpotency —
//! built directly on the Schreier–Sims substrate ([`PermGroup`]).
//!
//! These are *polynomial* in the group's degree and generator count (a bounded
//! number of `from_generators` rebuilds + membership tests), so they stay fast
//! on the large permutation groups where enumerating conjugacy classes is
//! intractable — the reason the degree-24 transitive catalog certifies
//! solvability through this path rather than via class computation.

use crate::bigint::BigUInt;
use crate::error::Result;
use crate::group::PermGroup;
use crate::perm::Perm;

/// A small generating set for the group `⟨gens⟩` of known `order` — greedily
/// keep only the generators that strictly increase the order. The result
/// generates the same group with ≤ `log₂(order)` generators (each kept one at
/// least doubles the order). Each trial builds a chain from a *small* prefix,
/// so this is cheap even when `gens` is large.
fn reduce_generators(degree: usize, gens: &[Perm], order: &BigUInt) -> Result<Vec<Perm>> {
    let mut kept: Vec<Perm> = Vec::new();
    let mut cur = BigUInt::one();
    for g in gens {
        if g.is_identity() {
            continue;
        }
        let mut trial = kept.clone();
        trial.push(g.clone());
        let o = PermGroup::from_generators(degree, &trial)?.order();
        if o > cur {
            cur = o;
            kept = trial;
            if &cur == order {
                break;
            }
        }
    }
    Ok(kept)
}

/// The normal closure `⟨seed⟩^G` — the smallest normal subgroup of `group`
/// containing the subgroup generated by `seed`.
///
/// BFS over the conjugation action: conjugate the *newly adjoined* generators
/// by `group`'s generators each round, adding any conjugate that escapes the
/// current closure, until closed (bounded above by `group`). The returned
/// group's generating set is **reduced to a small one** — essential, since the
/// derived / lower-central series feed it back through commutators of all
/// generator pairs (`O(gens²)`), which explodes without reduction.
pub fn normal_closure(group: &PermGroup, seed: &[Perm]) -> Result<PermGroup> {
    let degree = group.degree();
    let mut gens: Vec<Perm> = seed.iter().filter(|p| !p.is_identity()).cloned().collect();
    if gens.is_empty() {
        return PermGroup::from_generators(degree, &[]);
    }
    let mut h = PermGroup::from_generators(degree, &gens)?;
    let mut frontier = gens.clone();
    loop {
        let mut added: Vec<Perm> = Vec::new();
        for s in &frontier {
            for x in group.generators() {
                let c = s.conjugate(x)?;
                if !c.is_identity() && !h.contains(&c)? && !added.contains(&c) {
                    added.push(c);
                }
            }
        }
        if added.is_empty() {
            break;
        }
        gens.extend(added.iter().cloned());
        h = PermGroup::from_generators(degree, &gens)?;
        frontier = added;
    }
    // Reduce to a small generating set so downstream commutator passes stay cheap.
    let order = h.order();
    let reduced = reduce_generators(degree, &gens, &order)?;
    PermGroup::from_generators(degree, &reduced)
}

/// The derived (commutator) subgroup `G' = [G, G]` — the normal closure of the
/// commutators of `group`'s generators (these generate `G'` as a normal
/// subgroup). Trivial (order 1) iff `G` is abelian.
pub fn derived_subgroup(group: &PermGroup) -> Result<PermGroup> {
    let g = group.generators();
    let mut comms: Vec<Perm> = Vec::new();
    for a in g {
        for b in g {
            let c = a.commutator(b)?;
            if !c.is_identity() && !comms.contains(&c) {
                comms.push(c);
            }
        }
    }
    normal_closure(group, &comms)
}

/// Orders of the derived series `|G|, |G'|, |G''|, …` carried until it
/// stabilizes. The last entry is `1` iff `G` is solvable, else the order of the
/// perfect residual `G^(∞)`.
pub fn derived_series_orders(group: &PermGroup) -> Result<Vec<BigUInt>> {
    let mut orders = vec![group.order()];
    let mut current = group.clone();
    loop {
        let d = derived_subgroup(&current)?;
        if d.order() == current.order() {
            break;
        }
        orders.push(d.order());
        current = d;
    }
    Ok(orders)
}

/// Orders of the lower central series `|G|, |γ₂|, …` with `γ_{i+1} = [G, γ_i]`,
/// carried until it stabilizes. The last entry is `1` iff `G` is nilpotent.
pub fn lower_central_series_orders(group: &PermGroup) -> Result<Vec<BigUInt>> {
    let mut orders = vec![group.order()];
    let mut current = group.clone();
    loop {
        let mut comms: Vec<Perm> = Vec::new();
        for x in group.generators() {
            for h in current.generators() {
                let c = x.commutator(h)?;
                if !c.is_identity() && !comms.contains(&c) {
                    comms.push(c);
                }
            }
        }
        let next = normal_closure(group, &comms)?;
        if next.order() == current.order() {
            break;
        }
        orders.push(next.order());
        current = next;
    }
    Ok(orders)
}

/// Whether `G` is solvable — the derived series reaches the trivial group.
pub fn is_solvable(group: &PermGroup) -> Result<bool> {
    if group.is_full_symmetric() {
        return Ok(group.degree() <= 4);
    }
    if group.is_full_alternating() {
        return Ok(group.degree() <= 4);
    }
    Ok(derived_series_orders(group)?.last().unwrap().is_one())
}

/// Whether `G` is nilpotent — the lower central series reaches the trivial group.
pub fn is_nilpotent(group: &PermGroup) -> Result<bool> {
    if group.is_full_symmetric() {
        return Ok(group.degree() <= 2);
    }
    if group.is_full_alternating() {
        return Ok(group.degree() <= 3);
    }
    Ok(lower_central_series_orders(group)?.last().unwrap().is_one())
}

/// Whether `G` is perfect — `G = G'`.
pub fn is_perfect(group: &PermGroup) -> Result<bool> {
    if group.is_full_symmetric() {
        return Ok(group.degree() <= 1);
    }
    if group.is_full_alternating() {
        return Ok(group.degree() >= 5);
    }
    Ok(derived_subgroup(group)?.order() == group.order())
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::perm::Point;

    fn p(img: &[usize]) -> Perm {
        Perm::from_images(&img.iter().map(|&x| x as Point).collect::<Vec<_>>()).unwrap()
    }
    fn grp(degree: usize, gens: &[&[usize]]) -> PermGroup {
        PermGroup::from_generators(degree, &gens.iter().map(|g| p(g)).collect::<Vec<_>>()).unwrap()
    }
    fn ords(v: &[BigUInt]) -> Vec<String> {
        v.iter().map(|o| o.to_decimal()).collect()
    }

    fn c5() -> PermGroup {
        grp(5, &[&[1, 2, 3, 4, 0]])
    }
    fn s3() -> PermGroup {
        grp(3, &[&[1, 0, 2], &[1, 2, 0]])
    }
    fn s4() -> PermGroup {
        grp(4, &[&[1, 2, 3, 0], &[1, 0, 2, 3]])
    }
    fn a4() -> PermGroup {
        grp(4, &[&[1, 2, 0, 3], &[0, 2, 3, 1]])
    }
    fn a5() -> PermGroup {
        grp(5, &[&[1, 2, 3, 4, 0], &[0, 1, 3, 4, 2]])
    }

    #[test]
    fn full_symmetric_structure_uses_exact_order_thresholds() {
        for degree in 1..=7 {
            let generators = if degree == 1 {
                vec![]
            } else {
                vec![
                    Perm::from_images(
                        &(0..degree)
                            .map(|point| {
                                if point == 0 {
                                    1
                                } else if point == 1 {
                                    0
                                } else {
                                    point
                                }
                            })
                            .map(|point| point as Point)
                            .collect::<Vec<_>>(),
                    )
                    .unwrap(),
                    Perm::from_images(
                        &(0..degree)
                            .map(|point| ((point + 1) % degree) as Point)
                            .collect::<Vec<_>>(),
                    )
                    .unwrap(),
                ]
            };
            let symmetric = PermGroup::from_generators(degree, &generators).unwrap();
            assert!(symmetric.is_full_symmetric());
            assert_eq!(is_solvable(&symmetric).unwrap(), degree <= 4);
            assert_eq!(is_nilpotent(&symmetric).unwrap(), degree <= 2);
            assert_eq!(is_perfect(&symmetric).unwrap(), degree <= 1);
        }

        let alternating = a5();
        assert!(!alternating.is_full_symmetric());
        assert!(!is_solvable(&alternating).unwrap());
        assert!(is_perfect(&alternating).unwrap());
    }

    #[test]
    fn full_alternating_structure_uses_exact_order_thresholds() {
        let alternating_three = grp(3, &[&[1, 2, 0]]);
        assert!(alternating_three.is_full_alternating());
        assert!(is_solvable(&alternating_three).unwrap());
        assert!(is_nilpotent(&alternating_three).unwrap());
        assert!(!is_perfect(&alternating_three).unwrap());

        let alternating_four = a4();
        assert!(alternating_four.is_full_alternating());
        assert!(is_solvable(&alternating_four).unwrap());
        assert!(!is_nilpotent(&alternating_four).unwrap());
        assert!(!is_perfect(&alternating_four).unwrap());

        let alternating_five = a5();
        assert!(alternating_five.is_full_alternating());
        assert!(!is_solvable(&alternating_five).unwrap());
        assert!(!is_nilpotent(&alternating_five).unwrap());
        assert!(is_perfect(&alternating_five).unwrap());
    }
    fn d4() -> PermGroup {
        grp(4, &[&[1, 2, 3, 0], &[0, 3, 2, 1]])
    }

    #[test]
    fn derived_series_textbook() {
        assert_eq!(ords(&derived_series_orders(&c5()).unwrap()), ["5", "1"]);
        assert_eq!(
            ords(&derived_series_orders(&s3()).unwrap()),
            ["6", "3", "1"]
        );
        assert_eq!(
            ords(&derived_series_orders(&s4()).unwrap()),
            ["24", "12", "4", "1"]
        );
        assert_eq!(
            ords(&derived_series_orders(&a4()).unwrap()),
            ["12", "4", "1"]
        );
        assert_eq!(ords(&derived_series_orders(&a5()).unwrap()), ["60"]); // perfect
        assert_eq!(
            ords(&derived_series_orders(&d4()).unwrap()),
            ["8", "2", "1"]
        );
    }

    #[test]
    fn lower_central_series_textbook() {
        assert_eq!(
            ords(&lower_central_series_orders(&c5()).unwrap()),
            ["5", "1"]
        );
        assert_eq!(
            ords(&lower_central_series_orders(&s3()).unwrap()),
            ["6", "3"]
        ); // not nilpotent
        assert_eq!(
            ords(&lower_central_series_orders(&a4()).unwrap()),
            ["12", "4"]
        );
        assert_eq!(
            ords(&lower_central_series_orders(&d4()).unwrap()),
            ["8", "2", "1"]
        ); // class 2
    }

    #[test]
    fn predicates_textbook() {
        for (g, solv, nilp, perf) in [
            (c5(), true, true, false),
            (s3(), true, false, false),
            (s4(), true, false, false),
            (a4(), true, false, false),
            (a5(), false, false, true),
            (d4(), true, true, false),
        ] {
            assert_eq!(is_solvable(&g).unwrap(), solv);
            assert_eq!(is_nilpotent(&g).unwrap(), nilp);
            assert_eq!(is_perfect(&g).unwrap(), perf);
        }
    }

    #[test]
    fn nilpotent_implies_solvable() {
        for g in [c5(), s3(), s4(), a4(), a5(), d4()] {
            if is_nilpotent(&g).unwrap() {
                assert!(is_solvable(&g).unwrap());
            }
        }
    }

    #[test]
    fn normal_closure_of_trivial_is_trivial() {
        let g = s4();
        let n = normal_closure(&g, &[]).unwrap();
        assert_eq!(n.order().to_decimal(), "1");
    }
}
