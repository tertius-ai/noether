fn deserialize_prime_local_membership<'de, R, D>(
    deserializer: D,
) -> Result<PolynomialPrimeLocalMembership<R>, D::Error>
where
    R: crate::Field + Deserialize<'de>,
    R::Element: Deserialize<'de>,
    PolynomialPrimeLocalIdeal<R>: Deserialize<'de>,
    PolynomialPrimeLocalElement<R>: Deserialize<'de>,
    Ideal<super::PolynomialRing<R>>: Deserialize<'de>,
    D: Deserializer<'de>,
{
    let wire = PolynomialPrimeLocalMembershipWire::<R>::deserialize(deserializer)?;
    if wire.type_id != PRIME_LOCAL_MEMBERSHIP_TYPE_ID {
        return Err(serde::de::Error::custom(format!(
            "expected type {}, received {}",
            PRIME_LOCAL_MEMBERSHIP_TYPE_ID, wire.type_id
        )));
    }
    let supplied = PolynomialPrimeLocalMembership {
        ideal: wire.ideal,
        value: wire.value,
        colon_ideal: wire.colon_ideal,
        multiplier: wire.multiplier,
        quotients: wire.quotients,
    };
    supplied.verify().map_err(serde::de::Error::custom)?;
    Ok(supplied)
}

macro_rules! impl_prime_local_json {
    ($field:ty) => {
        impl<'de> Deserialize<'de> for PolynomialPrimeLocalIdeal<$field> {
            fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
            where
                D: Deserializer<'de>,
            {
                deserialize_prime_local_ideal(deserializer)
            }
        }

        impl PolynomialPrimeLocalIdeal<$field> {
            /// Deserialize and independently revalidate a prime-local ideal.
            pub fn from_json(value: &str) -> Result<Self, NoetherError> {
                serde_json::from_str(value)
                    .map_err(|error| NoetherError::Serialization(error.to_string()))
            }
        }

        impl<'de> Deserialize<'de> for PolynomialPrimeLocalMembership<$field> {
            fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
            where
                D: Deserializer<'de>,
            {
                deserialize_prime_local_membership(deserializer)
            }
        }

        impl PolynomialPrimeLocalMembership<$field> {
            /// Deserialize and independently revalidate membership evidence.
            pub fn from_json(value: &str) -> Result<Self, NoetherError> {
                serde_json::from_str(value)
                    .map_err(|error| NoetherError::Serialization(error.to_string()))
            }
        }
    };
}

